#!/usr/bin/env python3
"""Independent confirmation of the known answers in docs/blocks/crc.md.

Written by the property writer from the spec only. Two unrelated methods:

  A. bit-serial: the hardware rule exactly as the spec states it, fed one wire
     bit at a time (non-reflected register, bytes serialised LSB- or MSB-first).
  B. standard: the textbook byte-wise table-driven CRC with the Rocksoft
     parameters (refin/refout/xorout) from the CRC catalogue, giving the usual
     "check" value; then converted to what `value_o` must show (bit-reversed
     over W bits for reflected CRCs, because the hardware never reflects).

Also prints the 72-bit wire sequences. With --emit-sv FILE it writes the
per-step state tables used as lemmas by the known-answer monitors in
crc_props.sv (crc_ka_states.svh); they are only written when every known
answer has been confirmed by both methods.

Run: python3 known_answers.py [--emit-sv crc_ka_states.svh]
(exit status 1 on any disagreement)
"""

import sys

DATA = b"123456789"


def mask(w):
    return (1 << w) - 1


def bitrev(x, w):
    return int(format(x, "0%db" % w)[::-1], 2)


# --- A. bit-serial model of the spec's update rule --------------------------

def wire_bits(data, lsb_first):
    for byte in data:
        for i in range(8):
            yield (byte >> i) & 1 if lsb_first else (byte >> (7 - i)) & 1


def serial_states(w, poly, init, lsb_first, data=DATA):
    """state before the first bit and after each wire bit (73 values)"""
    m = mask(w)
    s = init & m
    states = [s]
    for b in wire_bits(data, lsb_first):
        fb = ((s >> (w - 1)) & 1) ^ b
        s = ((s << 1) & m) ^ (poly & m if fb else 0)
        states.append(s)
    return states


def serial(w, poly, init, xorout, lsb_first, data=DATA):
    s = serial_states(w, poly, init, lsb_first, data)[-1]
    value = s ^ (mask(w) if xorout else 0)
    return s, value


# --- B. standard table-driven CRC (Rocksoft model) ---------------------------

def make_table(w, poly, refin):
    """Byte table for a W-bit CRC. For W < 8 the register is kept
    left-justified in an 8-bit (or wider) working register, the usual trick."""
    table = []
    if refin:
        rpoly = bitrev(poly, w)
        for n in range(256):
            c = n
            for _ in range(8):
                c = (c >> 1) ^ rpoly if c & 1 else c >> 1
            table.append(c & mask(w))
    else:
        width = max(w, 8)
        shift = width - w
        top = 1 << (width - 1)
        p = poly << shift
        for n in range(256):
            c = n << (width - 8)
            for _ in range(8):
                c = ((c << 1) ^ p) if c & top else (c << 1)
                c &= mask(width)
            table.append(c)
    return table


def table_crc(w, poly, init, refin, refout, xorout, data=DATA):
    table = make_table(w, poly, refin)
    if refin:
        crc = bitrev(init, w)
        for byte in data:
            crc = (crc >> 8) ^ table[(crc ^ byte) & 0xFF]
        reg = crc  # reflected register
        out = reg if refout else bitrev(reg, w)
    else:
        width = max(w, 8)
        shift = width - w
        crc = init << shift
        for byte in data:
            crc = ((crc << 8) & mask(width)) ^ table[((crc >> (width - 8)) ^ byte) & 0xFF]
        reg = crc >> shift
        out = bitrev(reg, w) if refout else reg
    return out ^ xorout


# SV parameter names, in the order of KNOWN below
SV_NAMES = ["CRC32", "CRC16_USB", "CRC16_CCITT", "CRC15_CAN", "CRC8",
            "CRC5_USB", "PARITY_MSB", "PARITY_LSB"]


def emit_sv(path):
    lines = [
        "// GENERATED by known_answers.py --emit-sv -- do not edit.",
        "// Per-step states of each known-answer run (data \"123456789\"):",
        "// entry j (bits [32*j +: 32]) is state_o after j wire bits, j = 0..72.",
        "// Used as lemmas by rosetta_crc_ka_monitor; the end value is",
        "// cross-checked against the standard table-driven CRC by the script.",
    ]
    for sv, (name, w, poly, init, xo, lsb, spec, _) in zip(SV_NAMES, KNOWN):
        st = serial_states(w, poly, init, lsb)
        lines.append("// %s" % name)
        # wrap 6 per line
        items = ["32'h%08X" % v for v in reversed(st)]
        rows = [", ".join(items[i:i + 6]) for i in range(0, len(items), 6)]
        lines.append("localparam [73*32-1:0] KA_ST_%s = {" % sv)
        lines.append(",\n".join("    " + r for r in rows))
        lines.append("};")
    open(path, "w").write("\n".join(lines) + "\n")
    print("wrote %s" % path)


# --- the spec's table --------------------------------------------------------
# name, W, poly, init, xorout_on, lsb_first, spec value_o,
#   catalogue: (refin, refout, xorout, check)
KNOWN = [
    ("CRC-32 (Ethernet)", 32, 0x04C11DB7, 0xFFFFFFFF, 1, True, 0x649C2FD3,
     (True, True, 0xFFFFFFFF, 0xCBF43926)),
    ("CRC-16/USB", 16, 0x8005, 0xFFFF, 1, True, 0x132D,
     (True, True, 0xFFFF, 0xB4C8)),
    ("CRC-16/CCITT-FALSE", 16, 0x1021, 0xFFFF, 0, False, 0x29B1,
     (False, False, 0x0000, 0x29B1)),
    ("CRC-15/CAN", 15, 0x4599, 0x0000, 0, False, 0x059E,
     (False, False, 0x0000, 0x059E)),
    ("CRC-8", 8, 0x07, 0x00, 0, False, 0xF4,
     (False, False, 0x00, 0xF4)),
    ("CRC-5/USB", 5, 0x05, 0x1F, 1, True, 0x13,
     (True, True, 0x1F, 0x19)),
    ("Parity (even), MSB first", 1, 0x1, 0x0, 0, False, 0x1,
     (False, False, 0x0, None)),
    ("Parity (even), LSB first", 1, 0x1, 0x0, 0, True, 0x1,
     (True, True, 0x0, None)),
]


def main():
    ok = True
    print("data = %r, %d bits" % (DATA, 8 * len(DATA)))
    for lsb in (False, True):
        bits = "".join(str(b) for b in wire_bits(DATA, lsb))
        print("wire order %s: %s" % ("LSB-first" if lsb else "MSB-first", bits))
    ones = sum(bin(b).count("1") for b in DATA)
    print("ones in data = %d (parity %d)" % (ones, ones & 1))
    print()
    hdr = "%-26s %2s  %-10s %-10s %-10s %-10s %-10s %s"
    print(hdr % ("CRC", "W", "spec", "serial(A)", "table(B)", "B->value_o", "catalogue", "verdict"))
    for name, w, poly, init, xo, lsb, spec, (refin, refout, xorval, check) in KNOWN:
        # A: what the hardware shows
        _, val_a = serial(w, poly, init, xo, lsb)
        # B: textbook CRC; reflected CRCs show bit-reversed in value_o.
        #    (the hardware's 1-bit xorout means all-ones, so cfg xorout=1 <=> xorval=mask)
        assert (xorval == mask(w)) == bool(xo) or (xorval == 0 and not xo)
        if w == 1:
            std = ones & 1  # parity: there is no catalogue table for W=1
            std_b = std
        else:
            std = table_crc(w, poly, init, refin, refout, xorval)
            std_b = bitrev(std, w) if refin else std
        cat_ok = (check is None) or (std == check)
        agree = (val_a == std_b == spec) and cat_ok
        ok &= agree
        fw = (w + 3) // 4
        f = lambda v: ("%0*X" % (fw, v)) if v is not None else "-"
        print(hdr % (name, w, f(spec), f(val_a), f(std), f(std_b), f(check),
                     "OK" if agree else "*** MISMATCH ***"))
    print()
    print("ALL KNOWN ANSWERS CONFIRMED" if ok else "*** SPEC CONSTANT DISAGREES WITH SOFTWARE CRC ***")
    if ok and len(sys.argv) == 3 and sys.argv[1] == "--emit-sv":
        emit_sv(sys.argv[2])
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
