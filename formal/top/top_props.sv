// ===========================================================================
//  Chip-top checkers for tt_um_jesselevine727_rosetta (docs/blocks/top.md).
//
//  Written from top.md, architecture.md 9-10, decisions.md and the component
//  specs only. src/rosetta_top.sv was not read (only its standard Tiny
//  Tapeout port list); src/rosetta_lane.sv only for its port list.
//
//  OBSERVATION. Properties are about the TT ports and about the PORTS OF THE
//  INSTANCES that top.md section 1 names (u_xbar, u_host, u_seq, u_mem_prog,
//  u_mem_data, u_chan, gen_lane[L].u_lane), plus the SRAM macro pins inside
//  the proven wrappers (u_mem_*.u_sram.u_macro). Open-source Yosys has no
//  hierarchical references, so the proof top ties a bus `wb` (and `wb2` for a
//  second copy) to those flattened ports with `connect -set` (top_wb*.ys,
//  generated by gen_top.py); top_wb.svh names every slice w_<inst>_<port>
//  (copy B: v_<inst>_<port>). An instance missing or misnamed fails at
//  elaboration (connect -set cannot find the port): top.md 1 fixes the names.
//
//  CHECKERS (one per proof job, see the .sby files):
//    top_wire_props   W: every interconnect row of top.md 4, the TT mapping of
//                     top.md 2, reset distribution of top.md 3, the register
//                     read OR, `ena` unused, instance parameters. All
//                     components are SHELLS (free outputs), so each row is
//                     checked against arbitrary values (top_wire.sby).
//    top_chip_props   single copy, real shared blocks, lanes cut: reset and
//                     quiescence (T1 part, T3, T4), pin mapping and
//                     synchronisers (top.md 2, ruling 2/14/31), T5, T6, T7,
//                     T12 (top_chip.sby).
//    top_ni_props     T8 non-interference, two copies (top_ni.sby).
//    top_core_props   core-level covers, including the complete bring-up
//                     with a real lane (top_bringup.sby).
//
//  Spec readings (each a switchable define where a choice was made; listed
//  in the report):
//    R1  "rst_n of every block" is the synchronised reset rst_sync[1]
//        (top.md 3); u_mem_prog has no reset port (mem.md 2.1).
//    R2  Lane run_i: top.md 4 says u_seq.run_o, sequencer.md 7.1 says
//        lane_run_o[L]. The shell of u_seq assumes lane_run_o == run_o
//        (proven: seq a_p5_lane_run), so either wiring passes.
//    R3  Shared lane buses (park_op/ctl/data, cfg_reg/hi/data, cmd_data) are
//        checked only in cycles where the lane's own strobe is set: the lane
//        lemma (lane.md 9 property 3) makes their value irrelevant
//        otherwise. Define TOP_STRICT_SHARED to require plain wires.
//    R4  Lane ts_i = u_chan.ts_o[15:0] (lane.md 2.2, ruling 30).
//    R5  Pin path: ruling 2/14/31 (three flops pin -> lane, two pin -> host,
//        one on loopback); xbar.md's two-flop text is stale.
//    R6  "Data phase of a host read" (T3) = host cmd[7] = 1 and bitcnt >= 16
//        (host.md 3.2: MISO carries data from falling edge 16 until it
//        returns to 0 at falling edge 48).
//    R7  Register read: top.md 4 says "OR of hreg_rdata_o"; W checks the OR
//        literally. Define TOP_RD_OWNER to accept any combination equal to
//        it under the owners' proven zero-outside-own-addresses outputs.
//    R8  (W) of T2, "has been written": every bit of the word written since
//        reset (both halves; a half-word store writes one half).
// ===========================================================================

// ---------------------------------------------------------------------------
//  W: wiring of top.md 2, 3, 4 (all components are shells)
// ---------------------------------------------------------------------------
module top_wire_props (
    input wire                 clk, rst_n, ena,
    input wire [7:0]           ui_in, uio_in, uo_out, uio_out, uio_oe,
    input wire [`TOP_WBW-1:0]  wb
);
`define TOP_WB_WIRES
`include "top_wb.svh"
`undef TOP_WB_WIRES

    // ---- reset model (top.md 3): rst_i_n(t) = rst_n(t) & rst_n(t-1) & rst_n(t-2)
    // Async assertion, release at the second rising edge after rst_n rises.
    // With rst_n low in the first cycle this is exact from the first cycle
    // (the design's synchroniser flops are cleared asynchronously).
    logic p1, p2;
    always @(posedge clk) begin p1 <= rst_n; p2 <= p1; end
    wire rst_m = rst_n & p1 & p2;
    always @* if ($initstate) env_rst: assume (!rst_n);

    // ---- proven port properties of the shells used here
    //  seq a_p5_lane_run (formal/seq): lane_run_o == run_o
    always @* sh_seq_lane_run: assume (w_seq_lane_run_o == w_seq_run_o);

    wire [127:0] l_res_data = {w_l3_res_data_o, w_l2_res_data_o, w_l1_res_data_o, w_l0_res_data_o};

`ifdef TOP_RD_OWNER
    // Reading R7 (switchable): accept any read combination that equals the
    // OR given the owners' proven "0 for every address it does not own"
    // (host.md 4 ownership; seq/xbar/chan/mem_data port tables).
    wire [6:0] ra = w_host_hreg_addr_o;
    wire seq_own  = ra == 7'h04 || (ra >= 7'h10 && ra <= 7'h2F && ra[2:0] <= 3'd4);
    wire md_own   = ra == 7'h04 || (ra >= 7'h10 && ra <= 7'h2F && ra[2:0] >= 3'd5);
    wire chan_own = ra == 7'h03 || ra == 7'h06 || (ra >= 7'h08 && ra <= 7'h0B);
    wire xbar_own = ra >= 7'h40 && ra <= 7'h45;
    always @* begin
        if (!seq_own)  sh_rd_seq:  assume (w_seq_hreg_rdata_o == 32'd0);
        if (!md_own)   sh_rd_md:   assume (w_md_hreg_rdata_o == 32'd0);
        if (!chan_own) sh_rd_chan: assume (w_chan_hreg_rdata_o == 32'd0);
        if (!xbar_own) sh_rd_xbar: assume (w_xbar_hreg_rdata_o == 32'd0);
        if (ra == 7'h04) begin
            sh_rd_seq04: assume ((w_seq_hreg_rdata_o & ~32'h0000_0F0F) == 32'd0);
            sh_rd_md04:  assume ((w_md_hreg_rdata_o  & ~32'h0000_00F0) == 32'd0);
        end
    end
`endif

    always @* begin
        // ---------------- top.md 2: Tiny Tapeout mapping
        a_tt_ui:       assert (w_xbar_ui_in_i  == ui_in);
        a_tt_uio_in:   assert (w_xbar_uio_in_i == uio_in);
        a_tt_uo:       assert (uo_out  == w_xbar_uo_out_o);
        a_tt_uio_out:  assert (uio_out == w_xbar_uio_out_o);
        a_tt_uio_oe:   assert (uio_oe  == w_xbar_uio_oe_o);
        // ---------------- clock to every block (top.md 2: clk)
        a_clk:         assert (w_xbar_clk == clk && w_host_clk == clk && w_seq_clk == clk &&
                               w_mp_clk == clk && w_md_clk == clk && w_chan_clk == clk &&
                               w_l0_clk == clk && w_l1_clk == clk && w_l2_clk == clk && w_l3_clk == clk);
        // ---------------- top.md 3: synchronised reset to every block
        a_rst_xbar:    assert (w_xbar_rst_n == rst_m);
        a_rst_host:    assert (w_host_rst_n == rst_m);
        a_rst_seq:     assert (w_seq_rst_n  == rst_m);
        a_rst_md:      assert (w_md_rst_n   == rst_m);
        a_rst_chan:    assert (w_chan_rst_n == rst_m);
        a_rst_l0:      assert (w_l0_rst_n   == rst_m);
        a_rst_l1:      assert (w_l1_rst_n   == rst_m);
        a_rst_l2:      assert (w_l2_rst_n   == rst_m);
        a_rst_l3:      assert (w_l3_rst_n   == rst_m);
        // ---------------- top.md 4: interconnect
        a_ph_mp:       assert (w_mp_ph_i   == w_seq_ph_o);
        a_ph_md:       assert (w_md_ph_i   == w_seq_ph_o);
        a_ph_host:     assert (w_host_ph_i == w_seq_ph_o);
        a_pm_fetch:    assert (w_mp_fetch_addr_i == w_seq_pm_addr_o);
        a_pm_rd_seq:   assert (w_seq_pm_rdata_i  == w_mp_rdata_o);
        a_pm_rd_host:  assert (w_host_pm_rdata_i == w_mp_rdata_o);
        a_h_pm:        assert (w_mp_h_en_i == w_host_h_pm_en_o && w_mp_h_we_i == w_host_h_pm_we_o &&
                               w_mp_h_addr_i == w_host_h_pm_addr_o && w_mp_h_wdata_i == w_host_h_pm_wdata_o);
        a_dm_lane:     assert (w_md_dm_op_i == w_seq_dm_op_o && w_md_dm_off_i == w_seq_dm_off_o &&
                               w_md_dm_hmask_i == w_seq_dm_hmask_o && w_md_dm_wdata_i == w_seq_dm_wdata_o);
        a_dm_rd_seq:   assert (w_seq_dm_rdata_i  == w_md_rdata_o);
        a_dm_rd_host:  assert (w_host_dm_rdata_i == w_md_rdata_o);
        a_h_dm:        assert (w_md_h_en_i == w_host_h_dm_en_o && w_md_h_we_i == w_host_h_dm_we_o &&
                               w_md_h_addr_i == w_host_h_dm_addr_o && w_md_h_wdata_i == w_host_h_dm_wdata_o);
        a_q_qe:        assert (w_seq_qe_i == w_md_qe_o);
        a_q_qf:        assert (w_seq_qf_i == w_md_qf_o);
        a_q_qne:       assert (w_host_qne_i == w_md_qne_o);
        a_ch_req:      assert (w_chan_ch_put_i == w_seq_ch_put_o && w_chan_ch_get_i == w_seq_ch_get_o &&
                               w_chan_ch_idx_i == w_seq_ch_idx_o && w_chan_ch_wdata_i == w_seq_ch_wdata_o);
        a_ch_state:    assert (w_seq_ch_valid_i == w_chan_ch_valid_o && w_seq_ch_data_i == w_chan_ch_data_o);
        a_ts_seq:      assert (w_seq_ts_i == w_chan_ts_o);
        a_hreg_seq:    assert (w_seq_hreg_we_i == w_host_hreg_we_o && w_seq_hreg_addr_i == w_host_hreg_addr_o &&
                               w_seq_hreg_wdata_i == w_host_hreg_wdata_o);
        a_hreg_md:     assert (w_md_hreg_we_i == w_host_hreg_we_o && w_md_hreg_addr_i == w_host_hreg_addr_o &&
                               w_md_hreg_wdata_i == w_host_hreg_wdata_o);
        a_hreg_chan:   assert (w_chan_hreg_we_i == w_host_hreg_we_o && w_chan_hreg_addr_i == w_host_hreg_addr_o &&
                               w_chan_hreg_wdata_i == w_host_hreg_wdata_o);
        a_hreg_xbar:   assert (w_xbar_hreg_we_i == w_host_hreg_we_o && w_xbar_hreg_addr_i == w_host_hreg_addr_o &&
                               w_xbar_hreg_wdata_i == w_host_hreg_wdata_o);
        a_hreg_rd_or:  assert (w_host_hreg_rdata_i == (w_seq_hreg_rdata_o | w_md_hreg_rdata_o |
                                                       w_chan_hreg_rdata_o | w_xbar_hreg_rdata_o));
        a_run_md:      assert (w_md_run_i   == w_seq_run_o);
        a_run_xbar:    assert (w_xbar_run_i == w_seq_run_o);
        a_attn:        assert (w_host_attn_i == w_seq_attn_o);
        a_host_pins:   assert (w_host_sclk_i == w_xbar_host_sclk_o && w_host_csn_i == w_xbar_host_csn_o &&
                               w_host_mosi_i == w_xbar_host_mosi_o);
        a_host_miso:   assert (w_xbar_host_miso_i == w_host_miso_o);
        a_host_irq:    assert (w_xbar_host_irq_i  == w_host_irq_o);
        a_lane_res_data: assert (w_seq_lane_res_data_i == l_res_data);
    end

    // ---------------- per-lane rows (top.md 4 "lane pins", "lane control",
    // "run bits"; sequencer.md 2.6 / 7.1 / 7.2; lane L at [W*L +: W])
    wire [3:0]   l_run     = {w_l3_run_i, w_l2_run_i, w_l1_run_i, w_l0_run_i};
    wire [15:0]  l_in      = {w_l3_in_i, w_l2_in_i, w_l1_in_i, w_l0_in_i};
    wire [15:0]  l_val     = {w_l3_out_val_o, w_l2_out_val_o, w_l1_out_val_o, w_l0_out_val_o};
    wire [15:0]  l_oe      = {w_l3_out_oe_o, w_l2_out_oe_o, w_l1_out_oe_o, w_l0_out_oe_o};
    wire [3:0]   l_pwe     = {w_l3_park_we_i, w_l2_park_we_i, w_l1_park_we_i, w_l0_park_we_i};
    wire [3:0]   l_ack     = {w_l3_res_ack_i, w_l2_res_ack_i, w_l1_res_ack_i, w_l0_res_ack_i};
    wire [3:0]   l_abort   = {w_l3_abort_i, w_l2_abort_i, w_l1_abort_i, w_l0_abort_i};
    wire [15:0]  l_evclr   = {w_l3_ev_clr_i, w_l2_ev_clr_i, w_l1_ev_clr_i, w_l0_ev_clr_i};
    wire [3:0]   l_cfgwe   = {w_l3_cfg_we_i, w_l2_cfg_we_i, w_l1_cfg_we_i, w_l0_cfg_we_i};
    wire [7:0]   l_cmd     = {w_l3_cmd_i, w_l2_cmd_i, w_l1_cmd_i, w_l0_cmd_i};
    wire [3:0]   l_dwait   = {w_l3_data_wait_i, w_l2_data_wait_i, w_l1_data_wait_i, w_l0_data_wait_i};
    wire [63:0]  l_ts      = {w_l3_ts_i, w_l2_ts_i, w_l1_ts_i, w_l0_ts_i};
    wire [7:0]   l_pop     = {w_l3_park_op_i, w_l2_park_op_i, w_l1_park_op_i, w_l0_park_op_i};
    wire [111:0] l_pctl    = {w_l3_park_ctl_i, w_l2_park_ctl_i, w_l1_park_ctl_i, w_l0_park_ctl_i};
    wire [127:0] l_pdata   = {w_l3_park_data_i, w_l2_park_data_i, w_l1_park_data_i, w_l0_park_data_i};
    wire [19:0]  l_creg    = {w_l3_cfg_reg_i, w_l2_cfg_reg_i, w_l1_cfg_reg_i, w_l0_cfg_reg_i};
    wire [3:0]   l_chi     = {w_l3_cfg_hi_i, w_l2_cfg_hi_i, w_l1_cfg_hi_i, w_l0_cfg_hi_i};
    wire [63:0]  l_cdata   = {w_l3_cfg_data_i, w_l2_cfg_data_i, w_l1_cfg_data_i, w_l0_cfg_data_i};
    wire [127:0] l_cmdd    = {w_l3_cmd_data_i, w_l2_cmd_data_i, w_l1_cmd_data_i, w_l0_cmd_data_i};
    wire [3:0]   l_busy    = {w_l3_busy_o, w_l2_busy_o, w_l1_busy_o, w_l0_busy_o};
    wire [3:0]   l_pfull   = {w_l3_park_full_o, w_l2_park_full_o, w_l1_park_full_o, w_l0_park_full_o};
    wire [3:0]   l_rvalid  = {w_l3_res_valid_o, w_l2_res_valid_o, w_l1_res_valid_o, w_l0_res_valid_o};
    wire [15:0]  l_rdst    = {w_l3_res_dst_o, w_l2_res_dst_o, w_l1_res_dst_o, w_l0_res_dst_o};
    wire [63:0]  l_rts     = {w_l3_res_ts_o, w_l2_res_ts_o, w_l1_res_ts_o, w_l0_res_ts_o};
    wire [15:0]  l_dbusy   = {w_l3_dst_busy_o, w_l2_dst_busy_o, w_l1_dst_busy_o, w_l0_dst_busy_o};
    wire [3:0]   l_m       = {w_l3_m_o, w_l2_m_o, w_l1_m_o, w_l0_m_o};
    wire [15:0]  l_evp     = {w_l3_ev_pend_o, w_l2_ev_pend_o, w_l1_ev_pend_o, w_l0_ev_pend_o};
    wire [127:0] l_sr      = {w_l3_sr_o, w_l2_sr_o, w_l1_sr_o, w_l0_sr_o};
    wire [127:0] l_crc     = {w_l3_crc_o, w_l2_crc_o, w_l1_crc_o, w_l0_crc_o};

    for (genvar L = 0; L < 4; L++) begin : g_lane
        top_wire_lane u_lane (
            .run(l_run[L]), .seq_run(w_seq_run_o[L]),
            .in_i(l_in[4*L +: 4]), .x_in(w_xbar_lane_in_o[4*L +: 4]),
            .val(l_val[4*L +: 4]), .x_val(w_xbar_lane_val_i[4*L +: 4]),
            .oe(l_oe[4*L +: 4]), .x_oe(w_xbar_lane_oe_i[4*L +: 4]),
            .ts(l_ts[16*L +: 16]), .c_ts(w_chan_ts_o[15:0]),
            .pwe(l_pwe[L]), .s_pwe(w_seq_lane_park_we_o[L]),
            .ack(l_ack[L]), .s_ack(w_seq_lane_res_ack_o[L]),
            .abort(l_abort[L]), .s_abort(w_seq_lane_abort_o[L]),
            .evclr(l_evclr[4*L +: 4]), .s_evclr(w_seq_lane_ev_clr_o[4*L +: 4]),
            .cfgwe(l_cfgwe[L]), .s_cfgwe(w_seq_lane_cfg_we_o[L]),
            .cmd(l_cmd[2*L +: 2]), .s_cmd(w_seq_lane_cmd_o[2*L +: 2]),
            .dwait(l_dwait[L]), .s_dwait(w_seq_lane_data_wait_o[L]),
            .pop(l_pop[2*L +: 2]), .s_pop(w_seq_lane_park_op_o),
            .pctl(l_pctl[28*L +: 28]), .s_pctl(w_seq_lane_park_ctl_o),
            .pdata(l_pdata[32*L +: 32]), .s_pdata(w_seq_lane_park_data_o),
            .creg(l_creg[5*L +: 5]), .s_creg(w_seq_lane_cfg_reg_o),
            .chi(l_chi[L]), .s_chi(w_seq_lane_cfg_hi_o),
            .cdata(l_cdata[16*L +: 16]), .s_cdata(w_seq_lane_cfg_data_o),
            .cmdd(l_cmdd[32*L +: 32]), .s_cmdd(w_seq_lane_cmd_data_o),
            .busy(l_busy[L]), .s_busy(w_seq_lane_busy_i[L]),
            .pfull(l_pfull[L]), .s_pfull(w_seq_lane_park_full_i[L]),
            .rvalid(l_rvalid[L]), .s_rvalid(w_seq_lane_res_valid_i[L]),
            .rdst(l_rdst[4*L +: 4]), .s_rdst(w_seq_lane_res_dst_i[4*L +: 4]),
            .rts(l_rts[16*L +: 16]), .s_rts(w_seq_lane_res_ts_i[16*L +: 16]),
            .dbusy(l_dbusy[4*L +: 4]), .s_dbusy(w_seq_lane_dst_busy_i[4*L +: 4]),
            .m(l_m[L]), .s_m(w_seq_lane_m_i[L]),
            .evp(l_evp[4*L +: 4]), .s_evp(w_seq_lane_ev_pend_i[4*L +: 4]),
            .sr(l_sr[32*L +: 32]), .s_sr(w_seq_lane_sr_i[32*L +: 32]),
            .crc(l_crc[32*L +: 32]), .s_crc(w_seq_lane_crc_i[32*L +: 32])
        );
    end

    // ---------------- covers: the reset model and the shell assumption
    always @(posedge clk) begin
        c_rst_release: cover (rst_m && !$past(rst_m));
        c_rst_mid:     cover ($past(rst_m) && !rst_n);
        c_seq_run:     cover (w_seq_run_o == 4'b1010);
        c_strobes:     cover (rst_m && l_pwe == 4'b0101 && l_cfgwe == 4'b0010 && l_cmd[7:6] == 2'd2);
    end
endmodule

// One lane's rows of top.md 4 (lane pins, run bits, lane control per
// sequencer.md 2.6 / 7.1 / 7.2). Port names: lane side, s_/x_/c_ = the
// sequencer / crossbar / channel side the spec connects it to.
module top_wire_lane (
    input wire run, seq_run,
    input wire [3:0] in_i, x_in, val, x_val, oe, x_oe,
    input wire [15:0] ts, c_ts,
    input wire pwe, s_pwe, ack, s_ack, abort, s_abort,
    input wire [3:0] evclr, s_evclr,
    input wire cfgwe, s_cfgwe,
    input wire [1:0] cmd, s_cmd,
    input wire dwait, s_dwait,
    input wire [1:0] pop, s_pop,
    input wire [27:0] pctl, s_pctl,
    input wire [31:0] pdata, s_pdata,
    input wire [4:0] creg, s_creg,
    input wire chi, s_chi,
    input wire [15:0] cdata, s_cdata,
    input wire [31:0] cmdd, s_cmdd,
    input wire busy, s_busy, pfull, s_pfull, rvalid, s_rvalid,
    input wire [3:0] rdst, s_rdst,
    input wire [15:0] rts, s_rts,
    input wire [3:0] dbusy, s_dbusy,
    input wire m, s_m,
    input wire [3:0] evp, s_evp,
    input wire [31:0] sr, s_sr, crc, s_crc
);
    always @* begin
        a_run_lane:   assert (run == seq_run);
        a_lane_in:    assert (in_i == x_in);
        a_lane_val:   assert (x_val == val);
        a_lane_oe:    assert (x_oe == oe);
        a_lane_ts:    assert (ts == c_ts);
        a_lane_pwe:   assert (pwe == s_pwe);
        a_lane_ack:   assert (ack == s_ack);
        a_lane_abort: assert (abort == s_abort);
        a_lane_evclr: assert (evclr == s_evclr);
        a_lane_cfgwe: assert (cfgwe == s_cfgwe);
        a_lane_cmd:   assert (cmd == s_cmd);
        a_lane_dwait: assert (dwait == s_dwait);
`ifdef TOP_STRICT_SHARED
        a_lane_park_bus: assert (pop == s_pop && pctl == s_pctl && pdata == s_pdata);
        a_lane_cfg_bus:  assert (creg == s_creg && chi == s_chi && cdata == s_cdata);
        a_lane_cmd_bus:  assert (cmdd == s_cmdd);
`else
        if (pwe)         begin a_lane_park_bus: assert (pop == s_pop && pctl == s_pctl && pdata == s_pdata); end
        if (cfgwe)       begin a_lane_cfg_bus:  assert (creg == s_creg && chi == s_chi && cdata == s_cdata); end
        if (cmd == 2'd2) begin a_lane_cmd_bus:  assert (cmdd == s_cmdd); end
`endif
        a_seq_busy:   assert (s_busy == busy);
        a_seq_pfull:  assert (s_pfull == pfull);
        a_seq_rvalid: assert (s_rvalid == rvalid);
        a_seq_rdst:   assert (s_rdst == rdst);
        a_seq_rts:    assert (s_rts == rts);
        a_seq_dbusy:  assert (s_dbusy == dbusy);
        a_seq_m:      assert (s_m == m);
        a_seq_evp:    assert (s_evp == evp);
        a_seq_sr:     assert (s_sr == sr);
        a_seq_crc:    assert (s_crc == crc);
    end
endmodule

// ---------------------------------------------------------------------------
//  CHIP: one copy, real u_xbar / u_host / u_seq / u_chan / u_mem_* (the SRAM
//  macros free), lanes cut (shells: free outputs, nothing assumed about
//  them). Every property below holds for ANY lane behaviour.
//
//  Time base. rst_m is the checker's model of the internal reset (top.md 3).
//  Cycle 0 is the first cycle with rst_m = 1; cyc counts cycles from it
//  (saturating at 7) and ph_m = cycle mod 5 is the checker's OWN wheel
//  (sequencer.md 1: ph = t mod 5), independent of the design.
// ---------------------------------------------------------------------------
module top_chip_props (
    input wire                 clk, rst_n, ena,
    input wire [7:0]           ui_in, uio_in, uo_out, uio_out, uio_oe,
    input wire [`TOP_WBW-1:0]  wb
);
`define TOP_WB_WIRES
`include "top_wb.svh"
`undef TOP_WB_WIRES

    // ---------------------------------------------------------------- time
    logic p1, p2;
    always @(posedge clk) begin p1 <= rst_n; p2 <= p1; end
    wire rst_m = rst_n & p1 & p2;
    always @* if ($initstate) env_rst: assume (!rst_n);

    logic [2:0] cyc, ph_m;
    always @(posedge clk) begin
        cyc  <= !rst_m ? 3'd0 : (cyc == 3'd7) ? cyc : cyc + 3'd1;
        ph_m <= !rst_m ? 3'd0 : (ph_m >= 3'd4) ? 3'd0 : ph_m + 3'd1;
    end
    wire c0 = rst_m && cyc == 3'd0;
    wire [4:0] ph_1h = 5'b00001 << ph_m;

    // ------------------------------------------------- host request (u_host)
    wire hwe = w_host_hreg_we_o;
    wire [6:0] hadr = w_host_hreg_addr_o;
    wire [31:0] hwd = w_host_hreg_wdata_o;
    wire served_wr = hwe | (w_host_h_pm_en_o & w_host_h_pm_we_o) |
                     (w_host_h_dm_en_o & w_host_h_dm_we_o);
    logic wr_seen;
    logic [3:0] ctrl_on_seen;
    always @(posedge clk) begin
        wr_seen <= !rst_m ? 1'b0 : (wr_seen | served_wr);
        for (int L = 0; L < 4; L++)
            ctrl_on_seen[L] <= !rst_m ? 1'b0 :
                (ctrl_on_seen[L] | (hwe && hadr == 7'(7'h10 + 8*L) && hwd[0]));
    end

    // ------------------------- crossbar configuration shadow (xbar.md 4.3),
    // written from the HOST's register bus: checks the bus reaches u_xbar
    logic [63:0] sh_insel;
    logic [69:0] sh_outsel;
    logic        sh_loop;
    always @(posedge clk)
        if (!rst_m) begin
            sh_insel <= '0; sh_outsel <= '0; sh_loop <= 1'b0;
        end else if (hwe) begin
            if (hadr == 7'h40) sh_insel[31:0]   <= hwd;
            if (hadr == 7'h41) sh_insel[63:32]  <= hwd;
            if (hadr == 7'h42) sh_outsel[29:0]  <= hwd[29:0];
            if (hadr == 7'h43) sh_outsel[59:30] <= hwd[29:0];
            if (hadr == 7'h44) sh_outsel[69:60] <= hwd[9:0];
            if (hadr == 7'h45) sh_loop          <= hwd[0];
        end

    // ------------------------------------------------- histories
    wire [15:0] pins = {uio_in, ui_in};       // input index q (xbar.md 1)
    logic [15:0] d1, d2, d3;
    logic [7:0]  uo_d, uio_out_d, uio_oe_d;
    logic [63:0] insel_d;
    logic        loop_d;
    logic [2:0]  ph_d;
    logic        hwe_d;
    logic [6:0]  hadr_d;
    logic        hwd0_d;
    logic [69:0] outsel_d;
    logic [63:0] xinsel_d;
    logic        xloop_d;
    logic [15:0] qcfg_d;
    logic [27:0] inwr_d, outrd_d;
    logic [7:0]  imask_d;
    always @(posedge clk) begin
        d1 <= pins; d2 <= d1; d3 <= d2;
        uo_d <= uo_out; uio_out_d <= uio_out; uio_oe_d <= uio_oe;
        insel_d <= sh_insel; loop_d <= sh_loop;
        ph_d <= ph_m; hwe_d <= hwe; hadr_d <= hadr; hwd0_d <= hwd[0];
        outsel_d <= w_xbar_obs_outsel_o; xinsel_d <= w_xbar_obs_insel_o; xloop_d <= w_xbar_obs_loop_o;
        qcfg_d <= w_md_obs_qcfg_o; inwr_d <= w_md_obs_in_wr_o; outrd_d <= w_md_obs_out_rd_o;
        imask_d <= w_host_obs_imask_o;
    end

    // lane vectors (lane L at [W*L +: W])
    wire [3:0]  l_run  = {w_l3_run_i, w_l2_run_i, w_l1_run_i, w_l0_run_i};
    wire [15:0] l_in   = {w_l3_in_i, w_l2_in_i, w_l1_in_i, w_l0_in_i};
    wire [15:0] l_val  = {w_l3_out_val_o, w_l2_out_val_o, w_l1_out_val_o, w_l0_out_val_o};
    wire [15:0] l_oe   = {w_l3_out_oe_o, w_l2_out_oe_o, w_l1_out_oe_o, w_l0_out_oe_o};
    wire [3:0]  l_strobe = {
        w_l3_park_we_i | w_l3_res_ack_i | w_l3_abort_i | (|w_l3_ev_clr_i) | w_l3_cfg_we_i | (|w_l3_cmd_i),
        w_l2_park_we_i | w_l2_res_ack_i | w_l2_abort_i | (|w_l2_ev_clr_i) | w_l2_cfg_we_i | (|w_l2_cmd_i),
        w_l1_park_we_i | w_l1_res_ack_i | w_l1_abort_i | (|w_l1_ev_clr_i) | w_l1_cfg_we_i | (|w_l1_cmd_i),
        w_l0_park_we_i | w_l0_res_ack_i | w_l0_abort_i | (|w_l0_ev_clr_i) | w_l0_cfg_we_i | (|w_l0_cmd_i)};
    wire [63:0] l_ts = {w_l3_ts_i, w_l2_ts_i, w_l1_ts_i, w_l0_ts_i};
    wire [3:0]  run  = w_seq_run_o;

    // previous-cycle per-lane state for T4 (sequencer obs ports)
    logic [3:0]   run_d;
    logic [35:0]  pc_d;
    logic [255:0] r_d;
    logic [3:0]   z_d, n_d;
    always @(posedge clk) begin
        run_d <= l_run; pc_d <= w_seq_obs_pc_o; r_d <= w_seq_obs_r_o;
        z_d <= w_seq_obs_z_o; n_d <= w_seq_obs_n_o;
    end

    // D owner of the data stage (sequencer.md 1; mem.md 3.4)
    wire [1:0] downer = (ph_m == 3'd2) ? 2'd0 : (ph_m == 3'd3) ? 2'd1 :
                        (ph_m == 3'd4) ? 2'd2 : 2'd3;
    wire [8:0] fetch_pc = w_seq_obs_pc_o[9*ph_m[1:0] +: 9];

    always @* if (rst_m) begin
        // ======== reset state in cycle 0 (top.md 3 "After reset", 6 row 0)
        if (c0) begin
            a_c0_ph:    assert (w_seq_ph_o == 5'b00001);
            a_c0_ts:    assert (w_chan_ts_o == 32'd0);
            a_c0_run:   assert (run == 4'd0 && l_run == 4'd0 && w_seq_attn_o == 4'd0);
            a_c0_host:  assert (!w_host_miso_o && !w_host_irq_o && w_host_obs_imask_o == 8'd0 &&
                                w_host_obs_hst_o == 2'd0);
            a_c0_xbar:  assert (w_xbar_obs_outsel_o == 70'd0 && w_xbar_obs_insel_o == 64'd0 &&
                                !w_xbar_obs_loop_o);
            a_c0_queue: assert (w_md_obs_qcfg_o == 16'd0 && w_md_obs_in_wr_o == 28'd0 &&
                                w_md_obs_in_rd_o == 28'd0 && w_md_obs_out_wr_o == 28'd0 &&
                                w_md_obs_out_rd_o == 28'd0);
            a_c0_chan:  assert (w_chan_ch_valid_o == 4'd0);
            a_c0_pins:  assert (uo_out == 8'd0 && uio_out == 8'd0 && uio_oe == 8'd0);
            a_c0_lane_in: assert (l_in == 16'd0);
        end
        // ======== T3: quiet until configured
        if (!wr_seen) begin
            a_t3_quiet:      assert (uo_out[7:1] == 7'd0 && uio_out == 8'd0 && uio_oe == 8'd0);
            if (uo_out[0]) begin
                a_t3_quiet_miso: assert (w_host_obs_cmd_o[7] && w_host_obs_bitcnt_o >= 6'd16);
            end
        end
        // ======== T7: the wheel is the checker's own (sequencer.md 1)
        a_t7_wheel:   assert (w_seq_ph_o == ph_1h);
        if (w_chan_ch_put_i || w_chan_ch_get_i) begin
            a_t7_ch_slot: assert (ph_m != 3'd1);
        end
        // ======== T12: the host acts only in its slot (host.md property 1)
        if (w_host_h_pm_en_o) begin a_t12_pm_slot:  assert (ph_m == 3'd4); end
        if (w_host_h_dm_en_o) begin a_t12_dm_slot:  assert (ph_m == 3'd1); end
        if (hwe)              begin a_t12_reg_slot: assert (ph_m == 3'd1); end
        // ======== T6: memory accesses stay in their region / slot
        if (w_dmac_A_MEN && ph_m != 3'd1) begin
            a_t6_dm_region: assert (w_dmac_A_ADDR[8:7] == downer);
        end
        if (w_dmac_A_MEN && ph_m == 3'd1) begin
            a_t6_dm_host:   assert (w_host_h_dm_en_o && w_dmac_A_ADDR == w_host_h_dm_addr_o &&
                                    w_dmac_A_WEN == w_host_h_dm_we_o);
        end
        if (w_pmac_A_WEN && w_pmac_A_MEN) begin
            a_t6_pm_write:  assert (ph_m == 3'd4 && w_host_h_pm_en_o && w_host_h_pm_we_o &&
                                    w_pmac_A_ADDR == w_host_h_pm_addr_o && w_pmac_A_DIN == w_host_h_pm_wdata_o);
        end
        // a host request in its slot is served by the macro (mem.md 2.2, 3.4)
        if (ph_m == 3'd4 && w_host_h_pm_en_o) begin
            a_t6_pm_host:   assert (w_pmac_A_MEN && w_pmac_A_WEN == w_host_h_pm_we_o &&
                                    w_pmac_A_ADDR == w_host_h_pm_addr_o &&
                                    (!w_host_h_pm_we_o || (w_pmac_A_DIN == w_host_h_pm_wdata_o && w_pmac_A_BM == 32'hFFFFFFFF)));
        end
        if (ph_m == 3'd1 && w_host_h_dm_en_o) begin
            a_t6_dm_host_serv: assert (w_dmac_A_MEN && w_dmac_A_WEN == w_host_h_dm_we_o &&
                                       w_dmac_A_ADDR == w_host_h_dm_addr_o &&
                                       (!w_host_h_dm_we_o || (w_dmac_A_DIN == w_host_h_dm_wdata_o && w_dmac_A_BM == 32'hFFFFFFFF)));
        end
        // fetch (sequencer.md 4.2 + mem.md 2.2): ph = k <= 3 reads pc[k]
        if (ph_m <= 3'd3) begin
            a_fetch:        assert (w_pmac_A_MEN && w_pmac_A_REN && !w_pmac_A_WEN && w_pmac_A_ADDR == fetch_pc);
        end
        // ======== pins: host synchronisers (two flops, ruling 31)
        if (cyc >= 3'd2) begin
            a_pin_host_sync: assert ({w_host_mosi_i, w_host_csn_i, w_host_sclk_i} == d2[2:0]);
        end else begin
            a_pin_host_rst:  assert ({w_host_mosi_i, w_host_csn_i, w_host_sclk_i} == 3'b010);
        end
        a_pin_miso:  assert (uo_out[0] == w_host_miso_o);
        a_pin_irq:   assert (uo_out[1] == w_host_irq_o);
        // shadow of the crossbar configuration = the crossbar's own (helper,
        // and the end-to-end check of the register bus into u_xbar)
        a_cfg_shadow: assert (w_xbar_obs_insel_o == sh_insel && w_xbar_obs_outsel_o == sh_outsel &&
                              w_xbar_obs_loop_o == sh_loop);
    end

    // ---- previous-cycle values for the host read path and the IRQ
    wire [31:0] rd_or = w_seq_hreg_rdata_o | w_md_hreg_rdata_o | w_chan_hreg_rdata_o | w_xbar_hreg_rdata_o;
    wire [6:0]  hcmd_a = w_host_obs_cmd_o[6:0];
    wire reg_rd_svc = w_host_obs_hst_o == 2'd1 && ph_m == 3'd1 && w_host_obs_cmd_o[7] &&
                      hcmd_a != 7'h00 && hcmd_a != 7'h01 && hcmd_a != 7'h02 && hcmd_a != 7'h05;
    wire pm_rd_cap  = w_host_obs_hst_o == 2'd2 && ph_m == 3'd0 && !w_host_obs_maddr_o[9];
    wire dm_rd_cap  = w_host_obs_hst_o == 2'd2 && ph_m == 3'd2 &&  w_host_obs_maddr_o[9];
    logic        reg_rd_svc_d, pm_rd_cap_d, dm_rd_cap_d, chclr_d;
    logic [31:0] rd_or_d, pdout_d, ddout_d;
    logic [3:0]  chclr_m_d;
    logic        irq_exp_d;
    always @(posedge clk) begin
        reg_rd_svc_d <= reg_rd_svc; pm_rd_cap_d <= pm_rd_cap; dm_rd_cap_d <= dm_rd_cap;
        rd_or_d <= rd_or; pdout_d <= w_pmac_A_DOUT; ddout_d <= w_dmac_A_DOUT;
        chclr_d <= hwe && hadr == 7'h06; chclr_m_d <= hwd[3:0];
        irq_exp_d <= |(w_seq_attn_o & w_host_obs_imask_o[3:0]) | |(w_md_qne_o & w_host_obs_imask_o[7:4]);
    end

    always @(posedge clk) if (rst_m && cyc != 3'd0) begin
        // ======== interrupt output (host.md 5 / property 8, end to end at uo[1])
        a_irq:          assert (uo_out[1] == irq_exp_d);
        // ======== host CHSTAT write-1-to-clear reaches u_chan (channels.md 2)
        if (chclr_d) begin
            a_chstat_clr:  assert ((w_chan_ch_valid_o & chclr_m_d) == 4'd0);
        end
        // ======== host register read = OR of the owners' read buses (top.md 4)
        if (reg_rd_svc_d) begin
            a_reg_read:    assert (w_host_obs_sr_o == rd_or_d);
        end
        // ======== host memory read data (host.md 3.3: capture at ph 0 / ph 2)
        if (pm_rd_cap_d) begin
            a_pm_read:     assert (w_host_obs_sr_o == pdout_d);
        end
        if (dm_rd_cap_d) begin
            a_dm_read:     assert (w_host_obs_sr_o == ddout_d);
        end
    end

    // ======== T12: host-owned register effects only at the end of ph = 1
    always @(posedge clk) if (rst_m && cyc != 3'd0) begin
        if (w_xbar_obs_outsel_o != outsel_d || w_xbar_obs_insel_o != xinsel_d || w_xbar_obs_loop_o != xloop_d) begin
            a_t12_xbar_eff: assert (ph_d == 3'd1);
        end
        if (w_md_obs_qcfg_o != qcfg_d || w_md_obs_in_wr_o != inwr_d || w_md_obs_out_rd_o != outrd_d) begin
            a_t12_q_eff:    assert (ph_d == 3'd1);
        end
        if (w_host_obs_imask_o != imask_d) begin
            a_t12_imask_eff: assert (ph_d == 3'd1);
        end
    end

    // ------------------------------------------------ per lane: T3, T4, T7, pins
    for (genvar L = 0; L < 4; L++) begin : g_lane
        top_chip_lane #(.L(L)) u_l (
            .clk(clk), .rst_m(rst_m), .cyc(cyc), .ph_m(ph_m), .ph_d(ph_d),
            .run(l_run[L]), .run_d(run_d[L]), .seq_run(run[L]),
            .strobe(l_strobe[L]), .in_i(l_in[4*L +: 4]), .ts_i(l_ts[16*L +: 16]),
            .ts(w_chan_ts_o[15:0]),
            .dmac_men(w_dmac_A_MEN), .ch_op(w_chan_ch_put_i | w_chan_ch_get_i),
            .hwe_d(hwe_d), .hadr_d(hadr_d), .hwd0_d(hwd0_d),
            .pc(w_seq_obs_pc_o[9*L +: 9]), .pc_d(pc_d[9*L +: 9]),
            .r(w_seq_obs_r_o[64*L +: 64]), .r_d(r_d[64*L +: 64]),
            .zn({w_seq_obs_z_o[L], w_seq_obs_n_o[L]}), .zn_d({z_d[L], n_d[L]}),
            .insel_d(insel_d[16*L +: 16]), .loop_d(loop_d), .pins_d3(d3),
            .uo_d(uo_d), .uio_out_d(uio_out_d), .uio_oe_d(uio_oe_d)
        );
    end

    // ------------------------------------------------ per output pin p
    for (genvar P = 0; P < 14; P++) begin : g_pin
        wire pin_v  = (P < 6) ? uo_out[(P + 2) % 8] : uio_out[(P + 2) % 8];
        wire pin_oe = (P < 6) ? 1'b1 : uio_oe[(P + 2) % 8];
        top_chip_pin #(.P(P)) u_p (
            .rst_m(rst_m), .sel(sh_outsel[5*P +: 5]), .xsel(w_xbar_obs_outsel_o[5*P +: 5]),
            .run(run), .ctrl_on_seen(ctrl_on_seen), .l_val(l_val), .l_oe(l_oe),
            .pin_v(pin_v), .pin_oe(pin_oe)
        );
    end

    // ------------------------------------------------ covers
    // Without TOP_SPI_SCRIPT (cover task): shallow covers on free pins.
    // With TOP_SPI_SCRIPT (scover task, top_bringup.sby): the SPI pins
    // ui_in[2:0] are driven by a scripted master (top_spi_script) sending
    // three write frames at the fastest rate the host decodes; the deep
    // covers (served writes, a lane started, a pin driven) need them.
`ifndef TOP_SPI_SCRIPT
    always @(posedge clk) begin
        c_rst_release:  cover (c0);
        c_rst_again:    cover ($past(rst_m) && $past(cyc) == 3'd7 && !rst_n);
        c_miso_data:    cover (rst_m && !wr_seen && uo_out[0]);
        c_lane_in:      cover (rst_m && cyc == 3'd7 && l_in == 16'hFFFF);   // insel = 0: ui[0]
    end
`else
    (* anyconst *) logic [31:0] s_word;              // the program word
    wire s_sclk, s_csn, s_mosi, s_done;
    top_spi_script #(.NF(3)) u_script (
        .clk(clk), .rst_m(rst_m),
        .frames({8'h10, 32'h0000_0001,               // CTRL[0] = run
                 8'h42, 32'h0000_0010,               // XOUT0: uo[2] <- lane 0 out0, en
                 8'h02, s_word}),                    // MDATA (MADDR = 0 after reset)
        .sclk(s_sclk), .csn(s_csn), .mosi(s_mosi), .done(s_done));
    always @* begin
        env_spi_script: assume (ui_in[2:0] == {s_mosi, s_csn, s_sclk});
        if (!$initstate) env_no_rst: assume (rst_n);
    end
    logic pm0_written, run0_seen;
    logic [3:0] since_run0;
    always @(posedge clk) begin
        if (!rst_m) begin pm0_written <= 1'b0; run0_seen <= 1'b0; since_run0 <= 4'd0; end
        else begin
            if (w_pmac_A_MEN && w_pmac_A_WEN && w_pmac_A_ADDR == 9'd0 && w_pmac_A_DIN == s_word)
                pm0_written <= 1'b1;
            if (l_run[0] && !run_d[0] && pm0_written) run0_seen <= 1'b1;
            if (run0_seen && since_run0 != 4'hF) since_run0 <= since_run0 + 4'd1;
        end
    end
    always @(posedge clk) begin
        c_s_done:     cover (rst_m && s_done);    // the script ran to its end
        c_s_pm_write: cover (rst_m && pm0_written);
        c_s_xout:     cover (rst_m && w_xbar_obs_outsel_o[4:0] == 5'b10000);
        c_s_run0:     cover (rst_m && run0_seen);
        // complete bring-up: word 0 written by the host, lane 0 started at
        // PC 0, pin uo[2] driven by lane 0 within 8 cycles of the start (only
        // the first instruction can act that early: top.md 6)
        c_s_bringup:  cover (rst_m && pm0_written && run0_seen && since_run0 <= 4'd8 && uo_out[2]);
    end
`endif
endmodule

// Scripted SPI master for the deep covers: NF frames of NB bits (40: write
// frames; 48: also read frames, the host ignores MOSI after a write's 40th
// edge and during a read's dummy and data bits), frames[NB*f +: NB] = frame
// f, frame 0 first, MSB first, mode 0. One frame is PER = 2*NB + 16 cycles:
// CS_n low at offset 0, rising SCLK edges at offsets 5, 7, ..., 3 + 2*NB
// (one bit every 2 cycles, MOSI set with SCLK low), CS_n high from
// 2*NB + 8. The script starts 4 cycles after the internal reset release.
module top_spi_script #(parameter int NF = 3, parameter int NB = 40) (
    input wire clk, rst_m,
    input wire [NB*NF-1:0] frames,
    output logic sclk, csn, mosi, done
);
    localparam int PER = 2 * NB + 16;
    logic [10:0] cnt;
    always @(posedge clk)
        cnt <= !rst_m ? 11'd0 : (cnt == 11'h7FF) ? cnt : cnt + 11'd1;
    wire [10:0] t0  = (cnt >= 11'd4) ? cnt - 11'd4 : 11'd0;
    wire        act = rst_m && cnt >= 11'd4 && t0 < 11'(PER * NF);
    wire [10:0] f   = t0 / 11'(PER);
    wire [7:0]  o   = 8'(t0 % 11'(PER));
    wire [NB-1:0] w = frames[NB * f[3:0] +: NB];
    wire [7:0]  bo  = o - 8'd4;                // bit offset
    wire [6:0]  bi  = 7'(bo >> 1);              // bit index 0..NB-1
    wire        inb = o >= 8'd4 && o < 8'(2 * NB + 4);
    always @* begin
        csn  = !(act && o < 8'(2 * NB + 8));
        sclk = act && inb && bo[0];
        mosi = (act && inb) ? w[7'(NB - 1) - bi] : 1'b0;
        done = rst_m && cnt >= 11'd4 && t0 >= 11'(PER * NF);
    end
endmodule

// One lane of the chip checker (labels must be unique after flatten).
module top_chip_lane #(parameter int L = 0) (
    input wire clk, rst_m,
    input wire [2:0] cyc, ph_m, ph_d,
    input wire run, run_d, seq_run, strobe,
    input wire [3:0] in_i,
    input wire [15:0] ts_i, ts,
    input wire dmac_men, ch_op,
    input wire hwe_d,
    input wire [6:0] hadr_d,
    input wire hwd0_d,
    input wire [8:0] pc, pc_d,
    input wire [63:0] r, r_d,
    input wire [1:0] zn, zn_d,
    input wire [15:0] insel_d,
    input wire loop_d,
    input wire [15:0] pins_d3,
    input wire [7:0] uo_d, uio_out_d, uio_oe_d
);
    localparam logic [2:0] DPH = 3'((L + 2) % 5);   // L's D cycle
    localparam logic [2:0] XPH = 3'((L + 3) % 5);   // L's X cycle
    localparam logic [6:0] A_CTRL = 7'(7'h10 + 8*L);
    localparam logic [6:0] A_PC   = 7'(7'h11 + 8*L);

    // SRC(s) of xbar.md 4.1 on the previous cycle (loop: TT outputs; else
    // the pins three cycles back, ruling 31)
    function automatic logic src(input logic [3:0] s);
        if (!loop_d) src = pins_d3[s];
        else if (s < 8) src = uo_d[s[2:0]];
        else src = uio_oe_d[s[2:0]] ? uio_out_d[s[2:0]] : 1'b1;
    endfunction

    always @* if (rst_m) begin
        // ======== T4 (sequencer.md 9 property 7/8 seen at the lane's ports)
        a_t4_run_wire: assert (run == seq_run);
        if (!run) begin
            a_t4_no_strobe: assert (!strobe);
        end
        if (!run && ph_m == DPH) begin
            a_t4_no_dm: assert (!dmac_men);
            a_t4_no_ch: assert (!ch_op);
        end
        // ======== T7: lane-L strobes only in L's X cycle
        if (strobe) begin
            a_t7_strobe_slot: assert (ph_m == XPH);
        end
        // ======== timestamp (ruling 30, lane.md 2.2)
        a_lane_ts: assert (ts_i == ts);
        // ======== pins: lane inputs, three flops (ruling 2, 14, 31)
        if (cyc >= 3'd3) begin
            a_pin_lane_in: assert (in_i == {src(insel_d[15:12]), src(insel_d[11:8]),
                                            src(insel_d[7:4]), src(insel_d[3:0])});
        end
    end
    always @(posedge clk) if (rst_m && cyc != 3'd0) begin
        // ======== T4: run rises only by a host CTRL[L] write with bit 0
        if (run && !run_d) begin
            a_t4_run_rise: assert (ph_d == 3'd1 && hwe_d && hadr_d == A_CTRL && hwd0_d);
        end
        // ======== T4: a halted lane's PC, registers, Z, N change only by
        // host writes (PC[L])
        if (!run_d) begin
            if (!(hwe_d && ph_d == 3'd1 && hadr_d == A_PC)) begin
                a_t4_pc_frozen: assert (pc == pc_d);
            end
            a_t4_regs_frozen: assert (r == r_d && zn == zn_d);
        end
    end
endmodule

// One output pin p (xbar.md 1, 4.2; top.md 2, 5 "released"; T3, T5).
module top_chip_pin #(parameter int P = 0) (
    input wire rst_m,
    input wire [4:0] sel,       // shadow (from host writes)
    input wire [4:0] xsel,      // the crossbar's own select
    input wire [3:0] run, ctrl_on_seen,
    input wire [15:0] l_val, l_oe,
    input wire pin_v, pin_oe
);
    wire       en = sel[4];
    wire [1:0] ln = sel[3:2];
    wire [3:0] j  = {sel[3:2], sel[1:0]};
    wire drive    = en && run[ln] && l_oe[j];
    wire released = (P < 6) ? !pin_v : (!pin_oe && !pin_v);
    always @* if (rst_m) begin
        // output equations of xbar.md 4.2 through the TT mapping of top.md 2
        a_pin_out:      assert (pin_v == (drive && l_val[j]) && pin_oe == ((P < 6) ? 1'b1 : drive));
        if (!en) begin
            a_pin_unmapped: assert (released);
        end
        // T5: a halted or never-started lane enables no output
        if (xsel[4] && !run[xsel[3:2]]) begin
            a_t5_halted: assert (released);
        end
        // T3 part 2: until CTRL[L] bit 0 has been written, pins naming L released
        if (xsel[4] && !ctrl_on_seen[xsel[3:2]]) begin
            a_t3_lane_quiet: assert (released);
        end
    end
endmodule

// ---------------------------------------------------------------------------
//  T8 NON-INTERFERENCE (top.md 5 T8), core level, two copies A (wb) and B
//  (wb2) of the chip with u_host and all four lanes cut (shells), real
//  u_xbar / u_seq / u_chan / u_mem_*, and a PAIRED tracked-word model of each
//  SRAM (top_ni_mem). Fixed lane L (parameter). Every assumption below is
//  one of top.md T8's eight, as numbered there.
//
//  Lane L is a shell in both copies; T8 assumption 7 (the lane lemma) is
//  used as a RELATIONAL assumption on its outputs: lane.md 9 property 3
//  ("two copies with equal inputs except the shared buses in cycles where
//  the lane's own strobe is 0: every output is equal in every cycle"). The
//  checker keeps eqh = "lane L's inputs (modulo the lemma) have been equal
//  in A and B in every cycle so far" and assumes lane L's registered outputs
//  equal while eqh holds (out_oe_o, which lane.md 2 lets depend on run_i
//  combinationally, also needs run_i equal now). It then ASSERTS that the
//  inputs are equal in every cycle, which is the real content of T8 at the
//  top: the shared logic hands lane L the same inputs whatever the other
//  lanes and the host's other actions do.
// ---------------------------------------------------------------------------
module top_ni_props #(parameter int L = 0) (
    input wire                 clk, rst_n,
    input wire [7:0]           ui_a, uio_a, uo_a, uio_out_a, uio_oe_a,
    input wire [7:0]           ui_b, uio_b, uo_b, uio_out_b, uio_oe_b,
    input wire [`TOP_WBW-1:0]  wb, wb2,
    output wire [31:0]         dout_pa, dout_pb, dout_da, dout_db
);
`define TOP_WB_WIRES
`define TOP_WB2_WIRES
`include "top_wb.svh"
`undef TOP_WB_WIRES
`undef TOP_WB2_WIRES

    localparam logic [2:0] FPH = 3'(L);              // L's F cycle
    localparam logic [2:0] IPH = 3'((L + 1) % 5);    // I cycle
    localparam logic [2:0] DPH = 3'((L + 2) % 5);    // D cycle
    localparam logic [2:0] XPH = 3'((L + 3) % 5);    // X cycle
    localparam logic [6:0] A_CTRL = 7'(7'h10 + 8*L), A_PC = 7'(7'h11 + 8*L),
                           A_QCFG = 7'(7'h15 + 8*L), A_QIN = 7'(7'h16 + 8*L),
                           A_QOUT = 7'(7'h17 + 8*L), A_IRQSTAT = 7'h04;

    // ---------------------------------------------------------- time (A1)
    logic p1, p2;
    always @(posedge clk) begin p1 <= rst_n; p2 <= p1; end
    wire rst_m = rst_n & p1 & p2;
    always @* if ($initstate) env_rst: assume (!rst_n);
    logic [2:0] ph_m;
    always @(posedge clk) ph_m <= !rst_m ? 3'd0 : (ph_m >= 3'd4) ? 3'd0 : ph_m + 3'd1;
    wire [4:0] ph_1h = 5'b00001 << ph_m;

    // ---------------------------------------- A2: lane L's configuration
    wire [15:0] insel_a = w_xbar_obs_insel_o[16*L +: 16];
    wire [15:0] insel_b = v_xbar_obs_insel_o[16*L +: 16];
    always @* begin
        env_cfg_insel: assume (insel_a == insel_b);
        env_cfg_loop:  assume (!w_xbar_obs_loop_o && !v_xbar_obs_loop_o);
        env_cfg_qcfg:  assume (w_md_obs_qcfg_o[4*L +: 4] == v_md_obs_qcfg_o[4*L +: 4]);
    end
    for (genvar P = 0; P < 14; P++) begin : g_cfg
        wire [4:0] sa = w_xbar_obs_outsel_o[5*P +: 5];
        wire [4:0] sb = v_xbar_obs_outsel_o[5*P +: 5];
        top_ni_outsel_env #(.L(L)) u_e (.sa(sa), .sb(sb));
    end

    // ------------------------------------------------ A3: lane L's pins
    // The pin value that reaches the crossbar multiplexer is the pin two
    // cycles back (rulings 2, 14, 31); assumed equal in A and B for every
    // pin a lane-L input selects. Other pins free.
    wire [15:0] pins_a = {uio_a, ui_a}, pins_b = {uio_b, ui_b};
    logic [15:0] pa1, pa2, pb1, pb2;
    always @(posedge clk) begin pa1 <= pins_a; pa2 <= pa1; pb1 <= pins_b; pb2 <= pb1; end
    always @* begin
        env_pins0: assume (pa2[insel_a[3:0]]   == pb2[insel_a[3:0]]);
        env_pins1: assume (pa2[insel_a[7:4]]   == pb2[insel_a[7:4]]);
        env_pins2: assume (pa2[insel_a[11:8]]  == pb2[insel_a[11:8]]);
        env_pins3: assume (pa2[insel_a[15:12]] == pb2[insel_a[15:12]]);
    end

    // --------------------------------------- A4: host actions (core level)
    // u_host is cut: its request outputs are free in each copy, constrained
    // by the slot rule (top.md 5 core level = host.md property 1) and by
    // equality of every action on lane L.
    function automatic logic laneL_wr(input logic we, input logic [6:0] a, input logic [31:0] d);
        laneL_wr = we && (a == A_CTRL || a == A_PC || a == A_QCFG || a == A_QIN || a == A_QOUT ||
                          (a == A_IRQSTAT && d[L]));
    endfunction
    wire wl_a = laneL_wr(w_host_hreg_we_o, w_host_hreg_addr_o, w_host_hreg_wdata_o);
    wire wl_b = laneL_wr(v_host_hreg_we_o, v_host_hreg_addr_o, v_host_hreg_wdata_o);
    wire pw_a = w_host_h_pm_en_o && w_host_h_pm_we_o;
    wire pw_b = v_host_h_pm_en_o && v_host_h_pm_we_o;
    wire dw_a = w_host_h_dm_en_o && w_host_h_dm_we_o && w_host_h_dm_addr_o[8:7] == 2'(L);
    wire dw_b = v_host_h_dm_en_o && v_host_h_dm_we_o && v_host_h_dm_addr_o[8:7] == 2'(L);
    always @* begin
        if (!rst_m || ph_m != 3'd4) begin
            env_slot_pm_a: assume (!w_host_h_pm_en_o);
            env_slot_pm_b: assume (!v_host_h_pm_en_o);
        end
        if (!rst_m || ph_m != 3'd1) begin
            env_slot_dm_a: assume (!w_host_h_dm_en_o && !w_host_hreg_we_o);
            env_slot_dm_b: assume (!v_host_h_dm_en_o && !v_host_hreg_we_o);
        end
        env_one_a: assume (!(w_host_h_dm_en_o && w_host_hreg_we_o));
        env_one_b: assume (!(v_host_h_dm_en_o && v_host_hreg_we_o));
        env_host_laneL: assume (wl_a == wl_b && (!wl_a || (w_host_hreg_addr_o == v_host_hreg_addr_o &&
                                                           w_host_hreg_wdata_o == v_host_hreg_wdata_o)));
        env_host_pm:    assume (pw_a == pw_b && (!pw_a || (w_host_h_pm_addr_o == v_host_h_pm_addr_o &&
                                                           w_host_h_pm_wdata_o == v_host_h_pm_wdata_o)));
        env_host_dmL:   assume (dw_a == dw_b && (!dw_a || (w_host_h_dm_addr_o == v_host_h_dm_addr_o &&
                                                           w_host_h_dm_wdata_o == v_host_h_dm_wdata_o)));
    end

    // ------------------------------- A5: paired memory models (mem.md 4.2)
    (* anyconst *) logic [8:0] pa_trk, da_trk;
    wire [31:0] pd_a, pd_b, dd_a, dd_b;
    wire pvis, dvis, p_shared, d_shared;
    top_ni_mem #(.DATA(0), .L(L)) u_pmem (
        .clk(clk), .a_trk(pa_trk),
        .men_a(w_pmac_A_MEN), .wen_a(w_pmac_A_WEN), .ren_a(w_pmac_A_REN), .addr_a(w_pmac_A_ADDR),
        .din_a(w_pmac_A_DIN), .bm_a(w_pmac_A_BM),
        .men_b(v_pmac_A_MEN), .wen_b(v_pmac_A_WEN), .ren_b(v_pmac_A_REN), .addr_b(v_pmac_A_ADDR),
        .din_b(v_pmac_A_DIN), .bm_b(v_pmac_A_BM),
        .dout_a(dout_pa), .dout_b(dout_pb), .d_a(pd_a), .d_b(pd_b), .vis_trk(pvis), .shared(p_shared));
    top_ni_mem #(.DATA(1), .L(L)) u_dmem (
        .clk(clk), .a_trk(da_trk),
        .men_a(w_dmac_A_MEN), .wen_a(w_dmac_A_WEN), .ren_a(w_dmac_A_REN), .addr_a(w_dmac_A_ADDR),
        .din_a(w_dmac_A_DIN), .bm_a(w_dmac_A_BM),
        .men_b(v_dmac_A_MEN), .wen_b(v_dmac_A_WEN), .ren_b(v_dmac_A_REN), .addr_b(v_dmac_A_ADDR),
        .din_b(v_dmac_A_DIN), .bm_b(v_dmac_A_BM),
        .dout_a(dout_da), .dout_b(dout_db), .d_a(dd_a), .d_b(dd_b), .vis_trk(dvis), .shared(d_shared));

    // ------------------------------------------------ A6: no channel
    // IR in L's D cycle = program read data in L's I cycle (sequencer.md 4.2)
    logic [31:0] ir_q;
    always @(posedge clk) ir_q <= w_seq_pm_rdata_i;
    wire [3:0] op = ir_q[31:28];
    wire is_chan = (op == 4'd7  && ir_q[27:23] >= 5'd15 && ir_q[27:23] <= 5'd18) ||
                   (op == 4'd11 && ir_q[27:24] >= 4'd4  && ir_q[27:24] <= 4'd6) ||
                   ((op == 4'd0 || op == 4'd1) && (ir_q[17:16] == 2'b10 || ir_q[13:12] == 2'b10));
    // slot action EXEC (sequencer.md 4.3), from copy A (equal in B, asserted)
    wire elig = w_seq_run_o[L] && (!w_seq_obs_pause_o[L] || w_seq_obs_step_o[L]);
    wire [3:0] armed_a = w_seq_obs_armed_o[4*L +: 4];
    wire [3:0] lrv = {w_l3_res_valid_o, w_l2_res_valid_o, w_l1_res_valid_o, w_l0_res_valid_o};
    wire [15:0] lrd = {w_l3_res_dst_o, w_l2_res_dst_o, w_l1_res_dst_o, w_l0_res_dst_o};
    wire [15:0] lep = {w_l3_ev_pend_o, w_l2_ev_pend_o, w_l1_ev_pend_o, w_l0_ev_pend_o};
    wire exec_d = rst_m && ph_m == DPH && elig && !lrv[L] && ((lep[4*L +: 4] & armed_a) == 4'd0);
    always @* begin
        if (exec_d) begin env_no_chan: assume (!is_chan); end
        // derived: lane L never holds a result for a channel destination
        // (no FIELD/RAW with destination 8-11 is executed, assumption 6, and
        // lane.md 9 property 7: a result's destination is its park's)
        if (lrv[L]) begin env_no_chan_res: assume (lrd[4*L +: 4] < 4'd8 || lrd[4*L +: 4] > 4'd11); end
    end

    // ------------------------------------ A7: lane lemma, relational (A vs B)
    wire [5:0]   ra, rb;
    wire [79:0]  ia, ib;    // lane L's own inputs (not shared buses), A / B
    wire [61:0]  pka, pkb;  // park bus
    wire [21:0]  cfa, cfb;  // cfg bus
    wire [31:0]  cda, cdb;  // cmd data
    wire [131:0] oa, ob;    // registered outputs
    wire [3:0]   oea, oeb;  // out_oe_o
    top_ni_lanesel #(.L(L)) u_sa (
        .w0(wb), .ia(ia), .pk(pka), .cf(cfa), .cd(cda), .o(oa), .oe(oea));
    top_ni_lanesel #(.L(L)) u_sb (
        .w0(wb2), .ia(ib), .pk(pkb), .cf(cfb), .cd(cdb), .o(ob), .oe(oeb));
    // another lane M = L+1 (only for the cover of assumption 8: free outputs)
    wire [131:0] oma, omb;
    wire [3:0]   oema, oemb;
    top_ni_lanesel #(.L((L + 1) % 4)) u_sma (
        .w0(wb), .ia(), .pk(), .cf(), .cd(), .o(oma), .oe(oema));
    top_ni_lanesel #(.L((L + 1) % 4)) u_smb (
        .w0(wb2), .ia(), .pk(), .cf(), .cd(), .o(omb), .oe(oemb));
    // ia = {47'd0, rst_n, ts_i[15:0], in_i[3:0], data_wait_i, cmd_i[1:0], cfg_we_i,
    //       ev_clr_i[3:0], abort_i, res_ack_i, park_we_i, run_i} (top_ni_lanesel)
    wire pwe_a = ia[1], cfgwe_a = ia[8], run_a = ia[0];
    wire [1:0] cmd_a = ia[10:9];
    wire run_b = ib[0];
    wire in_eq = (ia == ib) && (!pwe_a || pka == pkb) && (!cfgwe_a || cfa == cfb) &&
                 (cmd_a != 2'd2 || cda == cdb);
    logic eqh;
    always @(posedge clk) eqh <= eqh && in_eq;
    always @* begin
        if ($initstate) env_eqh_init: assume (eqh);
        if (eqh) begin env_lemma: assume (oa == ob); end
        if (eqh && run_a == run_b) begin env_lemma_oe: assume (oea == oeb); end
    end

    // ================================================== CONCLUSIONS (T8)
    wire [3:0] rv = w_seq_run_o, rvb = v_seq_run_o;
    always @* begin
        // the history flag never drops (lane L's inputs always equal)
        a_ni_eqh:      assert (eqh);
        a_ni_lane_in:  assert (in_eq);
        a_ni_lane_out: assert (oa == ob && oea == oeb);
        // wheel and time are the same in both (helpers)
        if (rst_m) begin
            a_ni_ph:   assert (w_seq_ph_o == ph_1h && v_seq_ph_o == ph_1h);
        end
        a_ni_ts:       assert (w_chan_ts_o == v_chan_ts_o);
        // lane L's architectural state (sequencer obs ports, run, attn, qwait)
        a_ni_arch:     assert (w_seq_obs_pc_o[9*L +: 9]    == v_seq_obs_pc_o[9*L +: 9] &&
                               w_seq_obs_r_o[64*L +: 64]   == v_seq_obs_r_o[64*L +: 64] &&
                               w_seq_obs_z_o[L] == v_seq_obs_z_o[L] && w_seq_obs_n_o[L] == v_seq_obs_n_o[L] &&
                               w_seq_obs_pause_o[L] == v_seq_obs_pause_o[L] &&
                               w_seq_obs_step_o[L] == v_seq_obs_step_o[L] &&
                               w_seq_obs_armed_o[4*L +: 4] == v_seq_obs_armed_o[4*L +: 4] &&
                               w_seq_obs_tgt_o[36*L +: 36] == v_seq_obs_tgt_o[36*L +: 36] &&
                               w_seq_obs_wsta_o[L] == v_seq_obs_wsta_o[L] &&
                               w_seq_obs_capw_o[L] == v_seq_obs_capw_o[L] &&
                               rv[L] == rvb[L] && w_seq_attn_o[L] == v_seq_attn_o[L] &&
                               w_seq_lane_data_wait_o[L] == v_seq_lane_data_wait_o[L]);
        // lane L's queue pointers and sizes (mem_data obs ports)
        a_ni_queue:    assert (w_md_obs_qcfg_o[4*L +: 4]  == v_md_obs_qcfg_o[4*L +: 4] &&
                               w_md_obs_in_wr_o[7*L +: 7]  == v_md_obs_in_wr_o[7*L +: 7] &&
                               w_md_obs_in_rd_o[7*L +: 7]  == v_md_obs_in_rd_o[7*L +: 7] &&
                               w_md_obs_out_wr_o[7*L +: 7] == v_md_obs_out_wr_o[7*L +: 7] &&
                               w_md_obs_out_rd_o[7*L +: 7] == v_md_obs_out_rd_o[7*L +: 7]);
        // memory contents L can see (tracked words)
        if (pvis) begin a_ni_pmem: assert (pd_a == pd_b); end
        if (dvis) begin a_ni_dmem: assert (dd_a == dd_b); end
        // L's slot: data-memory request and macro access in L's D cycle,
        // instruction word in L's I cycle, read data in L's X cycle
        if (rst_m && ph_m == DPH) begin
            a_ni_dm_req:  assert (w_seq_dm_op_o == v_seq_dm_op_o && w_seq_dm_off_o == v_seq_dm_off_o &&
                                  w_seq_dm_hmask_o == v_seq_dm_hmask_o && w_seq_dm_wdata_o == v_seq_dm_wdata_o &&
                                  w_seq_ch_put_o == v_seq_ch_put_o && w_seq_ch_get_o == v_seq_ch_get_o);
            a_ni_dm_mac:  assert (w_dmac_A_MEN == v_dmac_A_MEN && w_dmac_A_WEN == v_dmac_A_WEN &&
                                  w_dmac_A_REN == v_dmac_A_REN &&
                                  (!w_dmac_A_MEN || w_dmac_A_ADDR == v_dmac_A_ADDR) &&
                                  (!(w_dmac_A_MEN && w_dmac_A_WEN) ||
                                   ((w_dmac_A_DIN & w_dmac_A_BM) == (v_dmac_A_DIN & v_dmac_A_BM) &&
                                    w_dmac_A_BM == v_dmac_A_BM)));
        end
        if (rst_m && ph_m == FPH) begin
            a_ni_fetch:   assert (w_pmac_A_ADDR == v_pmac_A_ADDR);
        end
        if (rst_m && ph_m == IPH) begin
            a_ni_ir:      assert (w_seq_pm_rdata_i == v_seq_pm_rdata_i);
        end
    end
    // read data in L's X cycle after L's own D-cycle read
    logic rd_d;
    always @(posedge clk) rd_d <= rst_m && ph_m == DPH && w_dmac_A_MEN && w_dmac_A_REN && !w_dmac_A_WEN;
    always @* if (rst_m && ph_m == XPH && rd_d) begin
        a_ni_dm_rdata: assert (w_seq_dm_rdata_i == v_seq_dm_rdata_i);
    end
    // pins whose selector names lane L (A2 makes the selector equal)
    for (genvar P = 0; P < 14; P++) begin : g_pin
        wire [4:0] sa = w_xbar_obs_outsel_o[5*P +: 5];
        wire va  = (P < 6) ? uo_a[(P + 2) % 8] : uio_out_a[(P + 2) % 8];
