// Paired tracked-word model of one SRAM macro for the two copies (mem.md
// 4.2, extended to two copies). One tracked address a_trk (anyconst, the
// same in both copies) with a word per copy, d_a / d_b, equal at power-up
// when a_trk is visible to lane L (T8 assumption 5: all of program memory;
// data memory region L). A read of a_trk returns the copy's tracked word; a
// read of any other address returns a free value, the SAME free value in
// both copies when both read the same visible address in the same cycle,
// independent values otherwise. Soundness: d_a == d_b is asserted for an
// arbitrary visible a_trk, so "every visible word is equal in both copies"
// holds in every cycle by induction over time; the shared value only uses
// that fact for reads, whose data reaches the design one cycle later.
// A_DOUT holds when there is no read (mem.md 1).
module top_ni_mem #(parameter int DATA = 0, parameter int L = 0) (
    input  wire        clk,
    input  wire [8:0]  a_trk,
    input  wire        men_a, wen_a, ren_a,
    input  wire [8:0]  addr_a,
    input  wire [31:0] din_a, bm_a,
    input  wire        men_b, wen_b, ren_b,
    input  wire [8:0]  addr_b,
    input  wire [31:0] din_b, bm_b,
    output logic [31:0] dout_a, dout_b,
    output logic [31:0] d_a, d_b,
    output wire        vis_trk, shared
);
    function automatic logic vis(input logic [8:0] a);
        vis = DATA ? (a[8:7] == 2'(L)) : 1'b1;
    endfunction
    (* anyseq *) logic [31:0] o_a, o_b, o_s;
    wire rd_a = men_a && ren_a && !wen_a, rd_b = men_b && ren_b && !wen_b;
    wire wr_a = men_a && wen_a,           wr_b = men_b && wen_b;
    assign vis_trk = vis(a_trk);
    assign shared  = rd_a && rd_b && addr_a == addr_b && vis(addr_a) && addr_a != a_trk;
    always @* if ($initstate && vis_trk) env_mem_init: assume (d_a == d_b);
    always @(posedge clk) begin
        if (wr_a && addr_a == a_trk) d_a <= (d_a & ~bm_a) | (din_a & bm_a);
        if (wr_b && addr_b == a_trk) d_b <= (d_b & ~bm_b) | (din_b & bm_b);
        if (wr_a && ren_a)  dout_a <= o_a;                      // write-through: never used
        else if (rd_a)      dout_a <= (addr_a == a_trk) ? d_a : shared ? o_s : o_a;
        if (wr_b && ren_b)  dout_b <= o_b;
        else if (rd_b)      dout_b <= (addr_b == a_trk) ? d_b : shared ? o_s : o_b;
    end
endmodule

