// ---------------------------------------------------------------------------
//  T9 LISTENER (top.md 5 T9), one copy, CORE level (u_host cut, request
//  interface free under the slot rule: this covers every request sequence
//  the real host can make, host.md property 1), real u_xbar / u_seq /
//  u_chan / u_mem_*, SRAM macros free, lanes cut.
//  E = the instruction forms that can enable a lane output, as lane.md 9
//  property 12 defines them at the lane's ports, mapped to instruction bits
//  (isa.md 3.1-3.4; park_op = IR[29:28], park_ctl = IR[27:0]):
//    FIELD (op 0) with kind IR[27:26] in {DRIVE 0, EXCHANGE 2};
//    RAW (op 1) with IR[27] = 1 (drive);
//    PIN (op 2) with (IR[27:24] & IR[19:16]) != 0 (an output changed to
//      enabled);
//    SETM (op 3) of TICK (register 0, low half) with bit 7 (clock output),
//      counting EVERY register-sourced SETM TICK (IR[21]) as E, since its
//      value is not in the instruction (conservative).
//  Premise for lane L: no EXEC slot of L (sequencer.md 4.3, action chosen in
//  L's D cycle) has had an E instruction in IR since reset. This is at least
//  as strong as top.md's "no EXEC slot commits an E instruction" (a waiting
//  EXEC also counts) and weaker than the compiler's rule (no E word in the
//  image at all).
//  Lane assumption (lane.md 9 property 12, the hardware half, port level):
//  if no E park (park_we_i with E content) and no SETM of TICK bit 7
//  (cfg_we_i, cfg_reg_i = 0, cfg_hi_i = 0, cfg_data_i[7]) has reached lane
//  L's ports since reset, then out_oe_o = 0.
//  Conclusion: lane L receives no E operation, its out_oe_o is 0, and every
//  pin whose selector names L is released.
// ---------------------------------------------------------------------------
module top_t9_props (
    input wire                 clk, rst_n, ena,
    input wire [7:0]           ui_in, uio_in, uo_out, uio_out, uio_oe,
    input wire [`TOP_WBW-1:0]  wb
);
`define TOP_WB_WIRES
`include "top_wb.svh"
`undef TOP_WB_WIRES
    logic p1, p2;
    always @(posedge clk) begin p1 <= rst_n; p2 <= p1; end
    wire rst_m = rst_n & p1 & p2;
    always @* if ($initstate) env_rst: assume (!rst_n);
    logic [2:0] ph_m;
    always @(posedge clk) ph_m <= !rst_m ? 3'd0 : (ph_m >= 3'd4) ? 3'd0 : ph_m + 3'd1;

    // core level (top.md 5): u_host is cut; its request interface is free
    // under the slot rule (host.md property 1); in reset it is idle.
    always @* begin
        if (!rst_m || ph_m != 3'd4) begin env_slot_pm: assume (!w_host_h_pm_en_o); end
        if (!rst_m || ph_m != 3'd1) begin env_slot_dm: assume (!w_host_h_dm_en_o && !w_host_hreg_we_o); end
        env_one: assume (!(w_host_h_dm_en_o && w_host_hreg_we_o));
    end

    always @(posedge clk) begin
        c_t9_hreg: cover (rst_m && w_host_hreg_we_o);
        c_t9_pm:   cover (rst_m && w_host_h_pm_en_o && w_host_h_pm_we_o);
        c_t9_dm:   cover (rst_m && w_host_h_dm_en_o);
    end

    logic [31:0] ir_q;                    // IR model (sequencer.md 4.2)
    always @(posedge clk) ir_q <= w_seq_pm_rdata_i;
    wire [3:0] op = ir_q[31:28];
    wire ir_e = (op == 4'd0 && (ir_q[27:26] == 2'd0 || ir_q[27:26] == 2'd2)) ||
                (op == 4'd1 && ir_q[27]) ||
                (op == 4'd2 && (ir_q[27:24] & ir_q[19:16]) != 4'd0) ||
                (op == 4'd3 && ir_q[27:23] == 5'd0 && !ir_q[22] && (ir_q[21] || ir_q[7]));

    wire [3:0]  lrv = {w_l3_res_valid_o, w_l2_res_valid_o, w_l1_res_valid_o, w_l0_res_valid_o};
    wire [15:0] lep = {w_l3_ev_pend_o, w_l2_ev_pend_o, w_l1_ev_pend_o, w_l0_ev_pend_o};
    wire [15:0] l_oe = {w_l3_out_oe_o, w_l2_out_oe_o, w_l1_out_oe_o, w_l0_out_oe_o};
    wire [3:0]  l_pwe = {w_l3_park_we_i, w_l2_park_we_i, w_l1_park_we_i, w_l0_park_we_i};
    wire [7:0]  l_pop = {w_l3_park_op_i, w_l2_park_op_i, w_l1_park_op_i, w_l0_park_op_i};
    wire [111:0] l_pctl = {w_l3_park_ctl_i, w_l2_park_ctl_i, w_l1_park_ctl_i, w_l0_park_ctl_i};
    wire [3:0]  l_cwe = {w_l3_cfg_we_i, w_l2_cfg_we_i, w_l1_cfg_we_i, w_l0_cfg_we_i};
    wire [19:0] l_creg = {w_l3_cfg_reg_i, w_l2_cfg_reg_i, w_l1_cfg_reg_i, w_l0_cfg_reg_i};
    wire [3:0]  l_chi = {w_l3_cfg_hi_i, w_l2_cfg_hi_i, w_l1_cfg_hi_i, w_l0_cfg_hi_i};
    wire [63:0] l_cdata = {w_l3_cfg_data_i, w_l2_cfg_data_i, w_l1_cfg_data_i, w_l0_cfg_data_i};

    for (genvar L = 0; L < 4; L++) begin : g_lane
        localparam logic [2:0] DPH = 3'((L + 2) % 5);
        wire elig  = w_seq_run_o[L] && (!w_seq_obs_pause_o[L] || w_seq_obs_step_o[L]);
        wire exec  = rst_m && ph_m == DPH && elig && !lrv[L] &&
                     ((lep[4*L +: 4] & w_seq_obs_armed_o[4*L +: 4]) == 4'd0);
        wire [27:0] c = l_pctl[28*L +: 28];
        wire [1:0]  po = l_pop[2*L +: 2];
        wire e_port = (l_pwe[L] && ((po == 2'd2 && (c[27:24] & c[19:16]) != 4'd0) ||
                                    (po == 2'd0 && (c[27:26] == 2'd0 || c[27:26] == 2'd2)) ||
                                    (po == 2'd1 && c[27]))) ||
                      (l_cwe[L] && l_creg[5*L +: 5] == 5'd0 && !l_chi[L] && l_cdata[16*L + 7]);
        top_t9_lane #(.L(L)) u_l (
            .clk(clk), .rst_m(rst_m), .exec_e(exec && ir_e), .e_port(e_port),
            .oe(l_oe[4*L +: 4]), .outsel(w_xbar_obs_outsel_o),
            .uo_out(uo_out), .uio_out(uio_out), .uio_oe(uio_oe));
    end
endmodule

module top_t9_lane #(parameter int L = 0) (
    input wire clk, rst_m, exec_e, e_port,
    input wire [3:0] oe,
    input wire [69:0] outsel,
    input wire [7:0] uo_out, uio_out, uio_oe
);
    logic listener, e_seen;               // since reset
    always @(posedge clk) begin
        listener <= !rst_m ? 1'b1 : listener && !exec_e;
        e_seen   <= !rst_m ? 1'b0 : e_seen || e_port;
    end
    // lane.md 9 property 12 (port level), lane L cut
    always @* if (!rst_m || !(e_seen || e_port)) begin
        env_lane_p12: assume (oe == 4'd0);
    end
    // released pins: p < 6 -> uo[p+2] = 0; p >= 6 -> uio_oe = uio_out = 0
    logic rel_ok;
    always @* begin
        rel_ok = 1'b1;
        for (int p = 0; p < 14; p++)
            if (outsel[5*p + 4] && outsel[5*p + 2 +: 2] == 2'(L)) begin
                if (p < 6) rel_ok &= !uo_out[(p + 2) % 8];
                else       rel_ok &= !uio_out[(p + 2) % 8] && !uio_oe[(p + 2) % 8];
            end
    end
    always @* if (rst_m && listener) begin
        a_t9_no_e_op:  assert (!e_seen && !e_port);
        a_t9_no_oe:    assert (oe == 4'd0);
        a_t9_released: assert (rel_ok);
    end
    always @(posedge clk) begin
        c_t9_listener_runs: cover (rst_m && listener && $past(exec_e == 1'b0) && outsel[4] && outsel[3:2] == 2'(L) &&
                                   $past(e_port == 1'b0));
        c_t9_talker:        cover (rst_m && !listener && oe != 4'd0);
    end
endmodule

// ---------------------------------------------------------------------------
//  T2 RESET DETERMINISM (top.md 5 T2), chip level, two copies A (wb) and B
//  (wb2) with IDENTICAL TT inputs in every cycle (rst_n low in the first),
//  every flop starting at an arbitrary, independent value. Real u_host,
//  u_xbar, u_seq, u_chan, u_mem_*; all four lanes cut, each under the
//  relational lane lemma (lane.md 9 property 3, as in T8: equal inputs so
//  far => equal outputs). SRAM contents and A_DOUT arbitrary and independent
//  (top_t2_mem): a read returns the SAME free value in both copies only for
//  a word written since reset (a per-address written bitmap, the
//  generalisation of mem.md 4.2's written_trk); a tracked address a_trk with
//  independent initial words d_a, d_b closes the argument (d_a == d_b once
//  written, asserted).
//  Assumption (W): every program word acted on by an EXEC slot, every word
//  the host reads, and every data word a lane reads has been written since
//  reset.
//  Conclusion: uo_out, uio_out, uio_oe equal in A and B in every cycle (and,
//  as the inductive strengthening, all observable state).
// ---------------------------------------------------------------------------
module top_t2_props (
    input wire                 clk, rst_n,
    input wire [2:0]           ui_in3,
    input wire [7:0]           uo_a, uio_out_a, uio_oe_a, uo_b, uio_out_b, uio_oe_b,
    input wire [`TOP_WBW-1:0]  wb, wb2,
    output wire [31:0]         dout_pa, dout_pb, dout_da, dout_db
);
`define TOP_WB_WIRES
`define TOP_WB2_WIRES
`include "top_wb.svh"
`undef TOP_WB_WIRES
`undef TOP_WB2_WIRES
    logic p1, p2;
    always @(posedge clk) begin p1 <= rst_n; p2 <= p1; end
    wire rst_m = rst_n & p1 & p2;
    always @* if ($initstate) env_rst: assume (!rst_n);
    logic [2:0] ph_m;
    always @(posedge clk) ph_m <= !rst_m ? 3'd0 : (ph_m >= 3'd4) ? 3'd0 : ph_m + 3'd1;

    // ---------------------------------------------------------- memories
    wire wp, wd;           // (W) premises: the read address was written
    wire [8:0] p_addr = w_pmac_A_ADDR, d_addr = w_dmac_A_ADDR;
    wire [31:0] pd_a, pd_b, dd_a, dd_b;
    wire [1:0] pwr, dwr;
    wire [511:0] pmap, dmap;
    top_t2_mem u_pmem (
        .clk(clk), .rst_m(rst_m),
        .men_a(w_pmac_A_MEN), .wen_a(w_pmac_A_WEN), .ren_a(w_pmac_A_REN), .addr_a(w_pmac_A_ADDR),
        .din_a(w_pmac_A_DIN), .bm_a(w_pmac_A_BM),
        .men_b(v_pmac_A_MEN), .wen_b(v_pmac_A_WEN), .ren_b(v_pmac_A_REN), .addr_b(v_pmac_A_ADDR),
        .din_b(v_pmac_A_DIN), .bm_b(v_pmac_A_BM),
        .dout_a(dout_pa), .dout_b(dout_pb), .d_a(pd_a), .d_b(pd_b), .wtrk(pwr), .wmap(pmap));
    top_t2_mem u_dmem (
        .clk(clk), .rst_m(rst_m),
        .men_a(w_dmac_A_MEN), .wen_a(w_dmac_A_WEN), .ren_a(w_dmac_A_REN), .addr_a(w_dmac_A_ADDR),
        .din_a(w_dmac_A_DIN), .bm_a(w_dmac_A_BM),
        .men_b(v_dmac_A_MEN), .wen_b(v_dmac_A_WEN), .ren_b(v_dmac_A_REN), .addr_b(v_dmac_A_ADDR),
        .din_b(v_dmac_A_DIN), .bm_b(v_dmac_A_BM),
        .dout_a(dout_da), .dout_b(dout_db), .d_a(dd_a), .d_b(dd_b), .wtrk(dwr), .wmap(dmap));

    // ---------------------------------------------------------- (W)
    wire p_rd = w_pmac_A_MEN && w_pmac_A_REN && !w_pmac_A_WEN;
    wire d_rd = w_dmac_A_MEN && w_dmac_A_REN && !w_dmac_A_WEN;
    // per lane: the word fetched in its F cycle (ph = L) had been written
    logic [3:0] fw;
    always @(posedge clk)
        if (ph_m <= 3'd3) fw[ph_m[1:0]] <= pmap[p_addr];
    wire [3:0]  lrv = {w_l3_res_valid_o, w_l2_res_valid_o, w_l1_res_valid_o, w_l0_res_valid_o};
    wire [15:0] lep = {w_l3_ev_pend_o, w_l2_ev_pend_o, w_l1_ev_pend_o, w_l0_ev_pend_o};
    wire [1:0]  dl  = (ph_m == 3'd2) ? 2'd0 : (ph_m == 3'd3) ? 2'd1 : (ph_m == 3'd4) ? 2'd2 : 2'd3;
    wire elig = w_seq_run_o[dl] && (!w_seq_obs_pause_o[dl] || w_seq_obs_step_o[dl]);
    wire exec = rst_m && ph_m != 3'd1 && elig && !lrv[dl] &&
                ((lep[4*dl +: 4] & w_seq_obs_armed_o[4*dl +: 4]) == 4'd0);
    always @* if (rst_m) begin
        if (p_rd && ph_m == 3'd4) begin env_w_host_pm: assume (pmap[p_addr]); end
        if (d_rd)                 begin env_w_dm:      assume (dmap[d_addr]); end
        if (exec)                 begin env_w_exec:    assume (fw[dl]); end
    end

    // ---------------------------------------------------- lanes: lemma
    logic [3:0] eqh;
    wire  [3:0] in_eq;
    for (genvar L = 0; L < 4; L++) begin : g_lane
        wire [79:0]  ia, ib;
        wire [61:0]  pka, pkb;
        wire [21:0]  cfa, cfb;
        wire [31:0]  cda, cdb;
        wire [131:0] oa, ob;
        wire [3:0]   oea, oeb;
        top_ni_lanesel #(.L(L)) u_sa (.w0(wb),  .ia(ia), .pk(pka), .cf(cfa), .cd(cda), .o(oa), .oe(oea));
        top_ni_lanesel #(.L(L)) u_sb (.w0(wb2), .ia(ib), .pk(pkb), .cf(cfb), .cd(cdb), .o(ob), .oe(oeb));
        assign in_eq[L] = (ia == ib) && (!ia[1] || pka == pkb) && (!ia[8] || cfa == cfb) &&
                          (ia[10:9] != 2'd2 || cda == cdb);
        // helper, in each copy (sequencer.md 9 property 5, proven for u_seq
        // and re-proven at the top as a_t7_strobe_slot / a_t4_no_strobe):
        // lane-L strobes only in L's X cycle and only while run[L]
        wire sa = ia[1] | ia[2] | ia[3] | (|ia[7:4]) | ia[8] | (|ia[10:9]);
        wire sb = ib[1] | ib[2] | ib[3] | (|ib[7:4]) | ib[8] | (|ib[10:9]);
        top_t2_lemma u_lm (.clk(clk), .eqh(eqh[L]), .run_eq(ia[0] == ib[0]),
                           .oa(oa), .ob(ob), .oea(oea), .oeb(oeb),
                           .strobe(rst_m && (sa || sb)),
                           .slot_ok(ph_m == 3'((L + 3) % 5) && ia[0] && ib[0]));
    end
    always @(posedge clk) eqh <= eqh & in_eq;
    always @* if ($initstate) env_eqh_init: assume (eqh == 4'hF);

    // ---------------------------------------------------- conclusions
    always @* begin
        a_t2_outputs: assert (uo_a == uo_b && uio_out_a == uio_out_b && uio_oe_a == uio_oe_b);
        // inductive strengthening: all observable state equal
        a_t2_eqh:     assert (eqh == 4'hF);
        a_t2_lane_in: assert (in_eq == 4'hF);
        a_t2_host:    assert (w_host_obs_sr_o == v_host_obs_sr_o && w_host_obs_cmd_o == v_host_obs_cmd_o &&
                              w_host_obs_bitcnt_o == v_host_obs_bitcnt_o && w_host_obs_maddr_o == v_host_obs_maddr_o &&
                              w_host_obs_hst_o == v_host_obs_hst_o && w_host_obs_imask_o == v_host_obs_imask_o &&
                              w_host_miso_o == v_host_miso_o && w_host_irq_o == v_host_irq_o &&
                              w_host_sclk_i == v_host_sclk_i && w_host_csn_i == v_host_csn_i &&
                              w_host_mosi_i == v_host_mosi_i);
        a_t2_seq_ph:  assert (w_seq_ph_o == v_seq_ph_o);
        a_t2_seq_run: assert (w_seq_run_o == v_seq_run_o && w_seq_attn_o == v_seq_attn_o);
        a_t2_seq_pc:  assert (w_seq_obs_pc_o == v_seq_obs_pc_o);
        a_t2_seq_r:   assert (w_seq_obs_r_o == v_seq_obs_r_o);
        a_t2_seq_zn:  assert (w_seq_obs_z_o == v_seq_obs_z_o && w_seq_obs_n_o == v_seq_obs_n_o);
        a_t2_seq_ctl: assert (w_seq_obs_pause_o == v_seq_obs_pause_o && w_seq_obs_step_o == v_seq_obs_step_o &&
                              w_seq_obs_armed_o == v_seq_obs_armed_o && w_seq_obs_tgt_o == v_seq_obs_tgt_o &&
                              w_seq_obs_wsta_o == v_seq_obs_wsta_o && w_seq_obs_capw_o == v_seq_obs_capw_o &&
                              w_seq_lane_data_wait_o == v_seq_lane_data_wait_o);
        a_t2_xbar:    assert (w_xbar_obs_insel_o == v_xbar_obs_insel_o && w_xbar_obs_outsel_o == v_xbar_obs_outsel_o &&
                              w_xbar_obs_loop_o == v_xbar_obs_loop_o && w_xbar_lane_in_o == v_xbar_lane_in_o);
        a_t2_chan:    assert (w_chan_ch_valid_o == v_chan_ch_valid_o && w_chan_ch_data_o == v_chan_ch_data_o &&
                              w_chan_ts_o == v_chan_ts_o);
        a_t2_mem:     assert (w_md_obs_qcfg_o == v_md_obs_qcfg_o && w_md_obs_in_wr_o == v_md_obs_in_wr_o &&
                              w_md_obs_in_rd_o == v_md_obs_in_rd_o && w_md_obs_out_wr_o == v_md_obs_out_wr_o &&
                              w_md_obs_out_rd_o == v_md_obs_out_rd_o);
        a_t2_pmac:    assert (w_pmac_A_MEN == v_pmac_A_MEN && w_pmac_A_WEN == v_pmac_A_WEN &&
                              w_pmac_A_REN == v_pmac_A_REN && w_pmac_A_ADDR == v_pmac_A_ADDR &&
                              w_pmac_A_DIN == v_pmac_A_DIN && w_pmac_A_BM == v_pmac_A_BM);
        a_t2_dmac:    assert (w_dmac_A_MEN == v_dmac_A_MEN && w_dmac_A_WEN == v_dmac_A_WEN &&
                              w_dmac_A_REN == v_dmac_A_REN && w_dmac_A_ADDR == v_dmac_A_ADDR &&
                              w_dmac_A_DIN == v_dmac_A_DIN && w_dmac_A_BM == v_dmac_A_BM);
        if (rst_m && pwr[0]) begin a_t2_ptrk_lo: assert (pd_a[15:0]  == pd_b[15:0]);  end
        if (rst_m && pwr[1]) begin a_t2_ptrk_hi: assert (pd_a[31:16] == pd_b[31:16]); end
        if (rst_m && dwr[0]) begin a_t2_dtrk_lo: assert (dd_a[15:0]  == dd_b[15:0]);  end
        if (rst_m && dwr[1]) begin a_t2_dtrk_hi: assert (dd_a[31:16] == dd_b[31:16]); end
    end
    // host read data and lane data reads of written words are equal (helper)
    logic hrp_d, hrd_d, lrd_d;
    always @(posedge clk) begin
        hrp_d <= rst_m && p_rd && ph_m == 3'd4;
        lrd_d <= rst_m && d_rd;
    end
    always @* begin
        if (rst_m && hrp_d) begin a_t2_prd: assert (w_pmac_A_DOUT == v_pmac_A_DOUT); end
        if (rst_m && lrd_d) begin a_t2_drd: assert (w_dmac_A_DOUT == v_dmac_A_DOUT); end
    end

    // ---------------------------------------------------- covers
`ifdef TOP_SPI_SCRIPT
    // (W) non-vacuity, chip level: frames MDATA write (word 0), MADDR = 0,
    // MDATA read of word 0 (host read of a written word), CTRL[0] = run
    // (lane 0 executes the written word 0). TT inputs are shared by A and B.
    (* anyconst *) logic [31:0] s_word;
    wire s_sclk, s_csn, s_mosi, s_done;
    top_spi_script #(.NF(4), .NB(48)) u_script (
        .clk(clk), .rst_m(rst_m),
        .frames({8'h10, 32'h0000_0001, 8'h00,      // CTRL[0] = run
                 8'h82, 40'h0,                     // MDATA read (MADDR = 0)
                 8'h01, 32'h0000_0000, 8'h00,      // MADDR = 0
                 8'h02, s_word, 8'h00}),           // MDATA write, word 0
        .sclk(s_sclk), .csn(s_csn), .mosi(s_mosi), .done(s_done));
    always @* begin
        env_spi_script: assume (ui_in3 == {s_mosi, s_csn, s_sclk});
        if (!$initstate) env_no_rst: assume (rst_n);
    end
    logic hrd_seen, exec_seen;
    always @(posedge clk) begin
        hrd_seen  <= !rst_m ? 1'b0 : hrd_seen  || (p_rd && ph_m == 3'd4 && pmap[p_addr]);
        exec_seen <= !rst_m ? 1'b0 : exec_seen || (exec && fw[dl]);
    end
    always @(posedge clk) begin
        c_t2_s_hostread: cover (rst_m && hrd_seen && s_done);
        c_t2_s_exec:     cover (rst_m && hrd_seen && exec_seen);
    end
`endif
    always @(posedge clk) begin
        c_t2_rst:       cover (rst_m && !$past(rst_m));
        c_t2_unwritten: cover (rst_m && p_rd && ph_m != 3'd4 && !pmap[p_addr] && w_pmac_A_DOUT != v_pmac_A_DOUT);
    end
endmodule

module top_t2_lemma (input wire clk, eqh, run_eq, input wire [131:0] oa, ob, input wire [3:0] oea, oeb,
                     input wire strobe, slot_ok);
    always @* if (strobe) begin a_t2_strobe_slot: assert (slot_ok); end
    always @* begin
        if (eqh)           begin env_lemma:    assume (oa == ob); end
        if (eqh && run_eq) begin env_lemma_oe: assume (oea == oeb); end
    end
endmodule

// T2 memory model for one macro (see top_t2_props): arbitrary independent
// contents; the same free read value in both copies only for halves written
// since reset (per-half written bitmaps; the wrappers' masks are whole
// halves, mem.md 3.4); a tracked address a_trk with independent initial
// words d_a, d_b. wmap[a] = both halves of word a written (what (W) needs).
module top_t2_mem (
    input  wire        clk, rst_m,
    input  wire        men_a, wen_a, ren_a,
    input  wire [8:0]  addr_a,
    input  wire [31:0] din_a, bm_a,
    input  wire        men_b, wen_b, ren_b,
    input  wire [8:0]  addr_b,
    input  wire [31:0] din_b, bm_b,
    output logic [31:0] dout_a, dout_b,
    output logic [31:0] d_a, d_b,
    output wire [1:0]   wtrk,
    output wire [511:0] wmap
);
    (* anyconst *) logic [8:0] a_trk;
    (* anyseq *) logic [31:0] o_a, o_b, o_s;
    logic [511:0] wlo, whi;
    assign wmap = wlo & whi;
    assign wtrk = {whi[a_trk], wlo[a_trk]};
    wire rd_a = men_a && ren_a && !wen_a, rd_b = men_b && ren_b && !wen_b;
    wire wr_a = men_a && wen_a,           wr_b = men_b && wen_b;
    wire same = rd_a && rd_b && addr_a == addr_b;
    wire [31:0] shm = {{16{same && whi[addr_a]}}, {16{same && wlo[addr_a]}}};
    always @(posedge clk) begin
        if (!rst_m) begin wlo <= '0; whi <= '0; end
        else if (wr_a) begin
            if (bm_a[15:0]  != 16'd0) wlo[addr_a] <= 1'b1;
            if (bm_a[31:16] != 16'd0) whi[addr_a] <= 1'b1;
        end
        if (wr_a && addr_a == a_trk) d_a <= (d_a & ~bm_a) | (din_a & bm_a);
        if (wr_b && addr_b == a_trk) d_b <= (d_b & ~bm_b) | (din_b & bm_b);
        if (wr_a && ren_a)  dout_a <= o_a;
        else if (rd_a)      dout_a <= (addr_a == a_trk) ? d_a : (o_s & shm) | (o_a & ~shm);
        if (wr_b && ren_b)  dout_b <= o_b;
        else if (rd_b)      dout_b <= (addr_b == a_trk) ? d_b : (o_s & shm) | (o_b & ~shm);
    end
endmodule

