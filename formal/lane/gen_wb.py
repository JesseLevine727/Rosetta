#!/usr/bin/env python3
"""Generate the white-box plumbing of the lane proof (layer W / E).

The lane checker observes the ports of the nine sub-block instances of the
design by their lane.md section 3 instance names (u_cfg, u_tick, ...). The
port lists are read from the proven sub-block sources in src/ (given
components; the lane RTL is NOT read). Outputs, both committed:

  lane_wb.svh   `define LANE_WBW and, for use inside lane_props, one named
                wire per observed port: w_<inst>_<port> = wb[off +: width]
  lane_<bus>.ys yosys commands run after `flatten` (lane.sby [script]):
                connect -set <bus>[hi:lo] <dut>.<inst>.<port>
                one file per (bus, dut) pair below.

A few internal flops of the sub-blocks (EXTRA) are also observed; they are
named in the sub-block RTL (given components) and used only by strengthening
lemmas (l_* in lane_props.sv).

Usage: python3 gen_wb.py   (run from formal/lane/)
"""
import re, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'src')

INSTS = [  # (instance, module file)
    ('u_cfg',   'rosetta_cfg'),
    ('u_tick',  'rosetta_tick'),
    ('u_dly',   'rosetta_delay'),
    ('u_code',  'rosetta_coding'),
    ('u_field', 'rosetta_field'),
    ('u_crc',   'rosetta_crc'),
    ('u_stuff', 'rosetta_stuff'),
    ('u_evt',   'rosetta_events'),
    ('u_pins',  'rosetta_pins'),
]

# internal flops (sub-block RTL names) used by lemmas only
EXTRA = [
    ('u_tick',  'stretch', 1), ('u_tick', 'srel', 1), ('u_tick', 'twq', 1), ('u_tick', 'ov', 1), ('u_tick', 'lr', 1),
    ('u_field', 'pk_op', 2), ('u_field', 'pk_ctl', 28),
    ('u_field', 'cu_op', 2), ('u_field', 'cu_ctl', 28),
    ('u_field', 'res_v', 1), ('u_field', 'res_dst', 4), ('u_field', 'hold', 1),
    ('u_field', 'first', 1), ('u_field', 'eff', 1), ('u_field', 'tail', 1),
    ('u_field', 'nl', 6), ('u_field', 'bc', 6), ('u_field', 'nlt', 1), ('u_field', 'nleq', 1),
    ('u_field', 'lnch', 1), ('u_field', 'lstf', 1), ('u_field', 'pstf', 1),
    ('u_tick', 'bt_ph', 1), ('u_tick', 'hw', 1), ('u_tick', 'sarm', 1),
    ('u_dly',   'pv', 1), ('u_dly', 'pclk', 1), ('u_dly', 'ppay', 5), ('u_dly', 'pcap', 1),
    ('u_code',  'hp', 1), ('u_code', 'hv', 1),
    ('u_pins',  'oe', 4), ('u_pins', 'val', 4),
    ('u_crc',   's', 32),
]

# (bus name in lane_fv, DUT instance path)
BUSES = [('wb_dut', 'u_dut'), ('wb_r53', 'u_r53')]


def ports(mod):
    txt = open(os.path.join(SRC, mod + '.sv')).read()
    m = re.search(r'module\s+' + mod + r'\b.*?\((.*?)\);', txt, re.S)
    hdr = m.group(1)
    # drop parameter block if present: the port list follows "#( ... ) ("
    if '#(' in txt[m.start():m.start() + 200]:
        m2 = re.search(r'module\s+' + mod + r'\s*#\s*\(.*?\)\s*\((.*?)\);', txt, re.S)
        hdr = m2.group(1)
    hdr = re.sub(r'//[^\n]*', '', hdr)
    out = []
    width = 1
    for decl in re.split(r',', hdr):
        d = decl.strip()
        if not d:
            continue
        mm = re.match(r'(input|output)\s+(wire|logic)?\s*(\[(\d+):(\d+)\])?\s*(\w+)$', d)
        if mm:
            width = int(mm.group(4)) - int(mm.group(5)) + 1 if mm.group(3) else 1
            name = mm.group(6)
        else:
            name = d.split()[-1]
        out.append((name, width))
    return out


def main():
    sigs = []
    for inst, mod in INSTS:
        for name, w in ports(mod):
            if name == 'clk':
                continue
            sigs.append((inst, name, w))
    sigs += EXTRA
    off = 0
    lay = []
    for inst, name, w in sigs:
        lay.append((inst, name, w, off))
        off += w
    total = off
    with open(os.path.join(HERE, 'lane_wb.svh'), 'w') as f:
        f.write('// GENERATED by gen_wb.py -- do not edit. White-box layout of the\n')
        f.write('// lane checker bus wb: one slice per observed sub-block port\n')
        f.write('// (lane.md 3 instance names) or internal flop (EXTRA).\n')
        f.write('`ifndef LANE_WB_LAYOUT\n`define LANE_WB_LAYOUT\n')
        f.write('`define LANE_WBW %d\n' % total)
        f.write('`endif\n')
        f.write('`ifdef LANE_WB_WIRES\n')
        for inst, name, w, o in lay:
            iname = inst[2:]
            f.write('wire [%d:0] w_%s_%s = wb[%d +: %d];\n' % (w - 1, iname, name, o, w))
        f.write('`endif\n')
    for bus, dut in BUSES:
        with open(os.path.join(HERE, 'lane_%s.ys' % bus), 'w') as f:
            f.write('# GENERATED by gen_wb.py -- do not edit. Run after flatten, in the\n')
            f.write('# proof top (cd lane_fv). Ties each slice of %s to the flattened\n' % bus)
            f.write('# sub-block port of %s (lane.md 3 instance names).\n' % dut)
            for inst, name, w, o in lay:
                f.write('connect -set %s[%d:%d] %s.%s.%s\n' % (bus, o + w - 1, o, dut, inst, name))
    print('LANE_WBW =', total, 'signals =', len(lay))


if __name__ == '__main__':
    main()
