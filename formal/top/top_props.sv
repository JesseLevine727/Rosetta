// ---------------------------------------------------------------------------
//  CORE-level bring-up cover (top.md 5 "core level": u_host cut, its request
//  interface free under the slot rule), with the REAL lanes and the full
//  SRAM models: the host writes program word 0 (ph = 4), maps uo[2] to lane
//  0 out0 (XOUT0, ph = 1), starts lane 0 (CTRL[0] = 1, ph = 1); lane 0
//  executes word 0 and drives uo[2] within 8 cycles of the start (top.md 6).
// ---------------------------------------------------------------------------
module top_core_props (
    input wire                 clk, rst_n, ena,
    input wire [7:0]           ui_in, uio_in, uo_out, uio_out, uio_oe,
    input wire [`TOP_WBW-1:0]  wb
);
`define TOP_WB_WIRES
`include "top_wb.svh"
`undef TOP_WB_WIRES
    logic p1, p2;
    always @(posedge clk) begin p1 <= rst_n; p2 <= p1; end
    wire rst_m = rst_n & p1 & p2;
    always @* begin
        if ($initstate) env_rst: assume (!rst_n);
        else            env_no_rst: assume (rst_n);
    end
    logic [2:0] ph_m;
    always @(posedge clk) ph_m <= !rst_m ? 3'd0 : (ph_m >= 3'd4) ? 3'd0 : ph_m + 3'd1;
    always @* begin
        if (!rst_m || ph_m != 3'd4) begin env_slot_pm: assume (!w_host_h_pm_en_o); end
        if (!rst_m || ph_m != 3'd1) begin env_slot_dm: assume (!w_host_h_dm_en_o && !w_host_hreg_we_o); end
        env_one: assume (!(w_host_h_dm_en_o && w_host_hreg_we_o));
    end
    logic pm0, xout, run0, run_q;
    logic [3:0] since;
    always @(posedge clk) run_q <= w_l0_run_i;
    always @(posedge clk)
        if (!rst_m) begin pm0 <= 1'b0; xout <= 1'b0; run0 <= 1'b0; since <= 4'd0; end
        else begin
            if (w_host_h_pm_en_o && w_host_h_pm_we_o && w_host_h_pm_addr_o == 9'd0) pm0 <= 1'b1;
            if (w_host_hreg_we_o && w_host_hreg_addr_o == 7'h42 && w_host_hreg_wdata_o[4:0] == 5'b10000) xout <= 1'b1;
            if (w_l0_run_i && !run_q && pm0 && xout) run0 <= 1'b1;  // started after the loads
            if (run0 && since != 4'hF) since <= since + 4'd1;
        end
    always @(posedge clk) begin
        c_core_pm0:     cover (rst_m && pm0);
        c_core_run0:    cover (rst_m && run0);
        c_core_bringup: cover (rst_m && pm0 && xout && run0 && since <= 4'd8 && uo_out[2] && w_l0_out_oe_o[0]);
    end
endmodule
